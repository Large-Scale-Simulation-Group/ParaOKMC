    def _create_changed_object_dtype(self) -> np.dtype:
        """
        Create CHANGED_OBJECT_DTYPE (object_dtype plus the old coordinates)

        Returns:
            object_dtype extended with old_x/old_y/old_z/old_valid

        Note:
        - active = False means the object was deleted
        - new = True means the object was created
        - changed = True means the object was modified
        - [pair-inc] old_* holds the coordinates before the change: the executing rank
          takes them from the self-contained event snapshot and broadcasts them, so every
          rank computes the old-position side of the poisoned zone identically (needed for
          deletions and long jumps). old_valid=False means there is no old position.
        """
        base = self.object_dtype
        names = list(base.names)
        formats = [base.fields[name][0] for name in names]
        names += ['old_x', 'old_y', 'old_z', 'old_valid']
        formats += [np.float64, np.float64, np.float64, np.bool_]
        return np.dtype({'names': names, 'formats': formats}, align=True)

    def _create_object_from_record(self, obj_rec: np.void, owner_rank: int) -> np.ndarray:
        """
        [optimization] Build an object straight from a NumPy record

        Copies a changed_object_dtype record into object_dtype without a dict in between

        Args:
            obj_rec: the NumPy record (changed_object_dtype)
            owner_rank: rank owning the object

        Returns:
            the object record (object_dtype)
        """
        obj = np.zeros(1, dtype=self.object_dtype)[0]

        # Copy the basic fields
        obj['id'] = obj_rec['id']
        obj['x'] = obj_rec['x']
        obj['y'] = obj_rec['y']
        obj['z'] = obj_rec['z']
        obj['owner_rank'] = owner_rank
        obj['active'] = obj_rec['active']

        # Copy type_id
        obj['type_id'] = obj_rec['type_id']

        # Copy the optional fields (when present)
        if 'size' in self.object_dtype.names:
            obj['size'] = obj_rec['size']

        if 'float_props' in self.object_dtype.names:
            obj['float_props'][:] = obj_rec['float_props']

        return obj

    def _serialize_changed_objects(self, changed_objects: List[Dict]) -> np.ndarray:
        """
        Serialize changed_objects (a list of dicts) into a NumPy structured array

        Args:
            changed_objects: list of changed object dicts

        Returns:
            the structured array (CHANGED_OBJECT_DTYPE)
        """
        if not changed_objects:
            return np.array([], dtype=self.changed_object_dtype)

        n = len(changed_objects)
        arr = np.zeros(n, dtype=self.changed_object_dtype)

        # Fetch the type_to_int mapping once (loop invariant)
        type_to_int = self.config.get('_type_to_int', {})

        for i, obj_dict in enumerate(changed_objects):
            # Fill the basic fields
            arr[i]['id'] = obj_dict.get('id', -1)
            arr[i]['x'] = obj_dict.get('x', 0.0)
            arr[i]['y'] = obj_dict.get('y', 0.0)
            arr[i]['z'] = obj_dict.get('z', 0.0)
            arr[i]['owner_rank'] = obj_dict.get('owner_rank', -1)
            arr[i]['active'] = obj_dict.get('active', True)

            # Fill type_id
            if 'type_id' in self.changed_object_dtype.names:
                if 'type_id' in obj_dict and obj_dict.get('type_id', -1) >= 0:
                    arr[i]['type_id'] = int(obj_dict['type_id'])
                else:
                    arr[i]['type_id'] = type_to_int.get(str(obj_dict.get('type', '')), -1)

            # [fix] Fill size: it used to be left out, so the receiver reclassified with a
            # zero value and a large object was demoted, losing its true radius
            if 'size' in self.changed_object_dtype.names:
                arr[i]['size'] = float(obj_dict.get('size', 0.0) or 0.0)

            # [pair-inc] Old coordinates (the old-position side of the zone)
            if 'old_valid' in self.changed_object_dtype.names:
                if obj_dict.get('old_valid', False):
                    arr[i]['old_x'] = float(obj_dict.get('old_x', 0.0))
                    arr[i]['old_y'] = float(obj_dict.get('old_y', 0.0))
                    arr[i]['old_z'] = float(obj_dict.get('old_z', 0.0))
                    arr[i]['old_valid'] = True

            # Fill the property arrays
            # [fix] The 'or []' guards against a user explicitly passing None
            if 'float_props' in self.object_dtype.names:
                float_props = obj_dict.get('float_props', []) or []
                max_float = self.object_dtype.fields['float_props'][0].shape[0]
                for j, val in enumerate(float_props[:max_float]):
                    arr[i]['float_props'][j] = val

            # Fill the flags (active was filled above)
            arr[i]['new'] = obj_dict.get('new', False)
            arr[i]['changed'] = obj_dict.get('changed', False)

        return arr

    def _deserialize_changed_objects(self, arr: np.ndarray) -> List[Dict]:
        """
        Deserialize a NumPy structured array back into changed_objects (a list of dicts)

        Args:
            arr: the structured array (CHANGED_OBJECT_DTYPE)

        Returns:
            the list of changed object dicts
        """
        changed_objects = []
        int_to_type = self.config.get('_int_to_type', {})

        for obj in arr:
            obj_dict = {
                'id': int(obj['id']),
                'type': int_to_type.get(int(obj['type_id']), ''),
                'x': float(obj['x']),
                'y': float(obj['y']),
                'z': float(obj['z']),
            }

            # [fix] Keep size (matching the serialization side)
            if 'size' in arr.dtype.names:
                obj_dict['size'] = float(obj['size'])

            # Add the property arrays (the non-zero part)
            if 'float_props' in self.object_dtype.names:
                float_props = obj['float_props'].tolist()
                # Keep the non-zero values only (0.0 is assumed to mark an unused slot)
                obj_dict['float_props'] = float_props

            # Add the flags (only when True)
            if obj['new']:
                obj_dict['new'] = True
            if obj['changed']:
                obj_dict['changed'] = True
            if not obj['active']:
                obj_dict['active'] = False

            changed_objects.append(obj_dict)

        return changed_objects

    def _bcast_changed_objects_zero_copy(self, changed_objects: Optional[List[Dict]],
                                          root: int,
                                          event_type: Optional[str] = None,
                                          dt: float = 0.0,
                                          param_update_flags: Optional[np.ndarray] = None,
                                          field_update_flags: Optional[np.ndarray] = None,
                                          global_update_flag: bool = False,
                                          event_category: str = 'none',
                                          local_idx: int = -1,
                                          physics_param_changes: Optional[List[Tuple[int, float]]] = None,
                                          physics_field_deltas: Optional[List[Tuple[int, float, float, float, float, float]]] = None
                                          ) -> Tuple[np.ndarray, str, float, np.ndarray, np.ndarray, bool, str, int, np.ndarray, np.ndarray]:
        """
        Broadcast changed_objects and the physics update decision without serialization

        [optimization] The physics update decision travels in the header, removing a deadlock
        - before: every rank decided on its own whether to update physics (deadlock risk)
        - now: the winner rank decides once and broadcasts

        [optimization 2] The event selection result travels in the header too
        - before: _select_event issued a separate Bcast(random)
        - now: the winner broadcasts event_category and local_idx together

        [fix] The flags grew from 64 to 256 bits (four uint64 words)
        - up to 256 parameters and 256 fields are supported

        Physics changes made while the event executes are broadcast as well
        - physics_param_changes: [(param_idx, new_value), ...]
        - physics_field_deltas: [(field_idx, x, y, z, delta, radius), ...]

        Args:
            changed_objects: the changed objects of the source rank (None elsewhere)
            root: the source rank
            event_type: event type string (only the root supplies it)
            dt: time step (only the root supplies it)
            param_update_flags: uint64[4] array of parameter update flags (256 parameters)
            field_update_flags: uint64[4] array of field update flags (256 fields)
            global_update_flag: whether the global update_func must be called
            event_category: event class ('zero', 'single', 'pair', 'none')
            local_idx: index of the event inside the local array
            physics_param_changes: parameter changes produced by the execution
            physics_field_deltas: field deltas produced by the execution

        Returns:
            (NumPy structured array, event_type, dt, param_flags[4], field_flags[4], global_flag,
             event_category, local_idx, param_changes_arr, field_deltas_arr)
        """
        # Extended header, including the counts of the physics changes
        header_dtype = np.dtype([
            ('event_type', 'S32'),           # a 32-byte ASCII string
            ('count', np.int64),             # number of changed objects
            ('dt', np.float64),              # the time step
            ('param_update_flags', np.uint64, (4,)),  # four uint64 words for 256 parameters
            ('field_update_flags', np.uint64, (4,)),  # four uint64 words for 256 fields
            ('global_update_flag', np.uint8),   # whether to call the global update_func
            ('event_category', 'S8'),        # event class ('zero', 'single', 'pair', 'none')
            ('local_idx', np.int32),         # index of the event inside the local array
            # New: counts of the physics changes produced by the execution
            ('n_param_changes', np.int32),   # number of parameter changes
            ('n_field_deltas', np.int32),    # number of field deltas
        ])
        header = np.zeros(1, dtype=header_dtype)

        # dtype of the physics changes
        param_change_dtype = np.dtype([
            ('param_idx', np.int32),
            ('value', np.float64),
        ])
        field_delta_dtype = np.dtype([
            ('field_idx', np.int32),
            ('x', np.float64),
            ('y', np.float64),
            ('z', np.float64),
            ('delta', np.float64),
            ('radius', np.float64),
        ])

        # Step 1: the source rank serializes the data and fills the header
        param_changes_arr = np.array([], dtype=param_change_dtype)
        field_deltas_arr = np.array([], dtype=field_delta_dtype)

        if self.rank == root:
            arr = self._serialize_changed_objects(changed_objects)
            header['count'][0] = len(arr)
            header['dt'][0] = dt

            # [fix] Copy the extended flag arrays
            if param_update_flags is not None:
                header['param_update_flags'][0][:] = param_update_flags
            if field_update_flags is not None:
                header['field_update_flags'][0][:] = field_update_flags

            header['global_update_flag'][0] = 1 if global_update_flag else 0
            header['event_category'][0] = event_category[:8].encode('ascii', errors='replace')
            header['local_idx'][0] = local_idx
            if event_type:
                header['event_type'][0] = event_type[:32].encode('ascii', errors='replace')

            # Serialize the physics changes
            if physics_param_changes:
                n_param = len(physics_param_changes)
                header['n_param_changes'][0] = n_param
                param_changes_arr = np.zeros(n_param, dtype=param_change_dtype)
                for i, (idx, val) in enumerate(physics_param_changes):
                    param_changes_arr[i]['param_idx'] = idx
                    param_changes_arr[i]['value'] = val

            if physics_field_deltas:
                n_field = len(physics_field_deltas)
                header['n_field_deltas'][0] = n_field
                field_deltas_arr = np.zeros(n_field, dtype=field_delta_dtype)
                for i, (idx, x, y, z, delta, radius) in enumerate(physics_field_deltas):
                    field_deltas_arr[i]['field_idx'] = idx
                    field_deltas_arr[i]['x'] = x
                    field_deltas_arr[i]['y'] = y
                    field_deltas_arr[i]['z'] = z
                    field_deltas_arr[i]['delta'] = delta
                    field_deltas_arr[i]['radius'] = radius
        else:
            arr = None

        # Step 2: broadcast the header
        self.comm.Bcast([header, MPI.BYTE], root=root)
        count = int(header['count'][0])
        event_type_str = header['event_type'][0].decode('ascii').strip('\x00')
        dt_out = float(header['dt'][0])

        # [fix] Extract the extended flag arrays
        param_flags_out = header['param_update_flags'][0].copy()
        field_flags_out = header['field_update_flags'][0].copy()

        global_flag_out = bool(header['global_update_flag'][0])
        event_category_out = header['event_category'][0].decode('ascii').strip('\x00')
        local_idx_out = int(header['local_idx'][0])

        # Extract the counts of the physics changes
        n_param_changes = int(header['n_param_changes'][0])
        n_field_deltas = int(header['n_field_deltas'][0])

        # Step 3: allocate the receive buffer
        if self.rank != root:
            arr = np.zeros(count, dtype=self.changed_object_dtype)
            if n_param_changes > 0:
                param_changes_arr = np.zeros(n_param_changes, dtype=param_change_dtype)
            if n_field_deltas > 0:
                field_deltas_arr = np.zeros(n_field_deltas, dtype=field_delta_dtype)

        # Step 4: broadcast the object data without serialization (when there is any)
        if count > 0:
            self.comm.Bcast([arr, MPI.BYTE], root=root)

        # Broadcast the physics changes (when there are any)
        if n_param_changes > 0:
            self.comm.Bcast([param_changes_arr, MPI.BYTE], root=root)
        if n_field_deltas > 0:
            self.comm.Bcast([field_deltas_arr, MPI.BYTE], root=root)

        return (arr, event_type_str, dt_out, param_flags_out, field_flags_out, global_flag_out,
                event_category_out, local_idx_out, param_changes_arr, field_deltas_arr)

    # ===== End of the serialization-free broadcast =====

    def run(self) -> Dict[str, Any]:
        """
        Run the OKMC simulation

        Returns:
            the run statistics
        """
        self.running = True
        _wall_t0 = time.perf_counter()  # wall-clock origin of the progress output

        # Print the initial state
        if self.progress_interval > 0 and self.rank == 0:
            print(f"[ParaOKMC] Starting simulation: max_steps={self.max_steps}, max_time={self.max_time:.2e}s", flush=True)

        # ===== Initialize the unified physics module =====
        # This must happen before the objects are created.
        # Reason: the user's initial_objects_func may place defects or dislocations
        #      according to a physical field (a stress field, say),
        # so the physical environment must exist before anything is born
        if self.physics is not None:
            self.physics.initialize()
            # [rate-invalidation] The parameters exist only now: build the rate
            # dependency tables (which event classes' rates use which parameter / field)
            self._build_rate_dependency_tables()

            if self.verbose and self.rank == 0:
                print(f"Physics initialized:")
                for name, idx, val in self.physics.list_params():
                    print(f"  param[{idx}] {name} = {val}")

        # Step 0: initialize the objects
        self._initialize_objects()

        if self.verbose and self.rank == 0:
            print(f"Initialized {self.rma_object_pool.get_local_count()} local objects")

        # sort_and_sync() must run after initialization to build the object classes
        self.rma_object_pool.sort_and_sync()

        if self.verbose and self.rank == 0:
            non_empty = len(self.rma_object_pool.get_non_empty_cells())
            print(f"Object classification done: {non_empty} non-empty cells")

        # Synchronize
        self.rma_object_pool.sync()

        # [Bug 1 fix] Initialization may have grown the boundary array, so the window must
        # be rebuilt collectively here or rebuild_ghost_cache() will read out of bounds
        # Scenario: initial_objects_func creates more objects than initial_capacity
        # -> add_object() triggers _expand_boundary_array()
        # -> _boundary_window_dirty = True while the window still points at the old buffer
        # -> the win_boundary.Get() of rebuild_ghost_cache() reads out of bounds -> segfault
        self.rma_object_pool.sync_window_rebuild()

        # Main loop
        while self.current_step < self.max_steps and self.current_time < self.max_time:
            # Set the current step so the random numbers stay globally consistent
            self.rng.set_step(self.current_step)

            # Step 1: build the events
            t0 = time.perf_counter()
            self._build_events()
            self.stats['build_time'] += time.perf_counter() - t0

            # [fix] step_completed must be called after _build_events
            # Reason: step_completed() clears changed_objects; called at the end of the loop,
            # the next _build_events() would see an empty set -> should_rebuild_single=False
            # -> the stale single events of deleted objects survive and recreate the object
            # Fix: move it after _build_events(), so changed_objects is consumed first
            self.incremental_manager.step_completed()

            # Step 1.5: predictive load balancing (optional)
            # The first step and the step after a repartition go full; the rest incremental (no pool reset)
            t0 = time.perf_counter()
            use_incremental = self.incremental_manager.enabled and not self._force_full_rebalance
            rebal_result = self.predictive_rebalancer.rebalance(
                self.rma_event_pool, incremental=use_incremental,
                step=self.current_step, force=self._force_full_rebalance)
            if isinstance(rebal_result, tuple):
                events_moved, sent_obj_ids, received_obj_ids = rebal_result
                self.incremental_manager.remove_migrated_obj_ids(sent_obj_ids)
                self.incremental_manager.add_migrated_obj_ids(received_obj_ids)
            else:
                events_moved = rebal_result
            self._force_full_rebalance = False
            self.stats['rebalance_time'] += time.perf_counter() - t0

            if self.verbose and self.rank == 0 and events_moved > 0:
                print(f"Step {self.current_step}: Predictive rebalance moved {events_moved} events")

            # Step 2: evaluate the rates
            t0 = time.perf_counter()
            self._compute_rates()
            self.stats['rate_time'] += time.perf_counter() - t0

            # Step 3: select an event
            t0 = time.perf_counter()
            total_rate = self._get_total_rate()

            # [fix] Do not exit on a zero local rate: every rank must join the reduction in _select_event
            # if total_rate <= 0:
            # if self.verbose and self.rank == 0:
            # print(f"Step {self.current_step}: Total rate is zero, stopping")
            # break

            winner_rank, event_category, local_idx, global_total_rate = self._select_event(total_rate)
            self.stats['select_time'] += time.perf_counter() - t0

            # [fix] The global selection result decides whether the run ends
            if winner_rank == -1:
                n_objs = self.rma_object_pool.get_local_count()
                cs = self.rma_event_pool.count_single
                cp = self.rma_event_pool.count_pair
                cz = self.rma_event_pool.count_zero
                s2_single = int(np.sum(self.rma_event_pool.single_obj_array[:cs]['status'] == 2)) if cs > 0 else 0
                s0_single = int(np.sum(self.rma_event_pool.single_obj_array[:cs]['status'] == 0)) if cs > 0 else 0
                print(f"[Rank {self.rank}] STOP step={self.current_step} "
                      f"local_rate={total_rate:.6e} objs={n_objs} "
                      f"zero={cz} single={cs}(s0={s0_single},s2={s2_single}) pair={cp}",
                      flush=True)
                break

            # Step 4: execute the event
            # Returns (dt, physics_changed), handling the time and physics updates together
            # [fix] dt is computed from global_total_rate (KMC requires dt = -ln(r)/R_global)
            t0 = time.perf_counter()
            dt, physics_changed = self._execute_event(winner_rank, event_category, local_idx, global_total_rate)
            self.stats['execute_time'] += time.perf_counter() - t0

            # sort_and_sync has been replaced by apply_changed_objects
            # The object classes are updated incrementally in _execute_event -> apply_changed_objects
            # so the O(N) reclassification of every step is gone

            # Step 5: advance the time
            # dt was computed by the winner rank inside _execute_event and broadcast
            self.current_time += dt

            # The physics update was handled inside _execute_event as well,
            # using the broadcast decision, which removes the deadlock risk
            if physics_changed and self.verbose and self.rank == 0:
                print(f"[Engine] Step {self.current_step}: physics changed, dependent rates invalidated")

            # [fix] Rebuild the RMA window before the post-processing
            # Reason: if _execute_event grew an array, the RMA window points at the old memory
            # and a post-processor reading neighbours over RMA would see stale or wrong data
            # Fix: move sync_window_rebuild ahead of post_processor.process
            self.rma_object_pool.sync_window_rebuild()

            # ===== Post-processing =====
            self.post_processor.process(
                self.current_step, self.current_time, self.rma_object_pool
            )

            # [fix] step_completed has moved after _build_events

            # [dynamic load balancing] Redistribute the objects periodically (RCB)
            should_rebal = self.object_load_balancer.should_rebalance(self.current_step)
            if should_rebal:
                import time as _time
                _t_rebal = _time.perf_counter()

                self.object_load_balancer.rebalance()

                # [fix] The caches must be invalidated after balancing
                # Reason: rebalance() updated ownership_map and the subdomain bounds moved
                # Without clearing the caches:
                # 1. domain_decomp.standard_ghost_cells follows the old bounds and may miss neighbours
                # (invalidate_ghost_cache now recomputes ghost_ranks too, since RCB
                # changes the rank adjacency)
                # 2. objects in rma_object_pool.ghost_cache may no longer be ghosts
                self.domain_decomp.invalidate_ghost_cache()
                self.rma_object_pool.invalidate_ghost_cache()

                # [fix] After ObjectLB the next step rebuilds the events in full (by design):
                # migrated objects carry no new/changed flag and never enter the coin, so the
                # incremental path would strip their single events for good (dropped by the
                self.incremental_manager.mark_global_state_changed()

                if self.rank == 0:
                    _elapsed_rebal = _time.perf_counter() - _t_rebal
                    print(f"[ObjectLB] Step {self.current_step}: rebalance completed in {_elapsed_rebal:.3f}s")

                # After a repartition the predictive rebalancer goes full next step
                self._force_full_rebalance = True

            self.current_step += 1
                # [fix] Only rank 0 counts the steps as events (no double counting)
                # or use a MAX reduction instead of SUM
            if self.rank == 0:
                self.stats['total_events'] += 1

            # Is a weight update due?
            if self.adaptive_weight_tracker.should_update_weights(self.current_step):
                updated_weights = self.adaptive_weight_tracker.update_weights(self.current_step)

                # Apply the updated weights to the event builder
                if updated_weights:
                    self.event_builder.event_weights.update(updated_weights)

                    if self.verbose and self.rank == 0:
                        print(f"Step {self.current_step}: Applied updated weights to event builder")

            if self.verbose and self.rank == 0 and self.current_step % 100 == 0:
                print(f"Step {self.current_step}: time={self.current_time:.6f}")

            # Progress output (independent of verbose, driven by progress_interval)
            if self.progress_interval > 0 and self.current_step % self.progress_interval == 0 and self.rank == 0:
                wall_elapsed = time.perf_counter() - _wall_t0
                n_objs = self.rma_object_pool.get_local_count()
                n_objs_global = self.comm.allreduce(n_objs, op=MPI.SUM)
                print(
                    f"[ParaOKMC] step={self.current_step:>8d}  "
                    f"sim_t={self.current_time:.4e}s  "
                    f"wall={wall_elapsed:>7.1f}s  "
                    f"objs={n_objs_global}",
                    flush=True
                )
            elif self.progress_interval > 0 and self.current_step % self.progress_interval == 0:
                # The other ranks join the allreduce
                n_objs = self.rma_object_pool.get_local_count()
                self.comm.allreduce(n_objs, op=MPI.SUM)

        self.running = False

        # ===== Final frame =====
        # The in-loop post-processing fires every `interval` steps, so a run that stops on
        # max_steps, max_time or a vanished total rate would otherwise leave no record of its
        # final state. Run it once more here, bypassing the interval; a frame already written
        # at this step is not repeated. This is what makes ic.mode='dump' a restart.
        self.rma_object_pool.sync_window_rebuild()
        self.post_processor.process(
            self.current_step, self.current_time, self.rma_object_pool, force=True
        )

        # Print the final state
        if self.progress_interval > 0 and self.rank == 0:
            wall_total = time.perf_counter() - _wall_t0
            n_objs = self.rma_object_pool.get_local_count()
            n_objs_global = self.comm.allreduce(n_objs, op=MPI.SUM)
            print(
                f"[ParaOKMC] Done: step={self.current_step}  "
                f"sim_t={self.current_time:.4e}s  "
                f"wall={wall_total:.1f}s  objs={n_objs_global}",
                flush=True
            )
            # Performance breakdown
            n = max(1, self.current_step)
            print(f"[ParaOKMC] Perf: build={self.stats['build_time']/n*1e3:.1f}ms "
                  f"rate={self.stats['rate_time']/n*1e3:.1f}ms "
                  f"select={self.stats['select_time']/n*1e3:.1f}ms "
                  f"exec={self.stats['execute_time']/n*1e3:.1f}ms "
                  f"per_step={wall_total/n*1e3:.1f}ms",
                  flush=True)
        elif self.progress_interval > 0:
            n_objs = self.rma_object_pool.get_local_count()
            self.comm.allreduce(n_objs, op=MPI.SUM)

        # Print the adaptive weight tracker summary
        if self.adaptive_weight_tracker.enabled:
            self.adaptive_weight_tracker.print_summary()

        # Print the object load balancer summary
        if self.object_load_balancer.enabled:
            self.object_load_balancer.print_summary()

        # Print the unified physics summary (verbose runs only)
        if self.physics is not None and self.verbose:
            self.physics.print_summary()

        # Return the statistics
        return self._collect_stats()

    def _initialize_objects(self):
        """Initialize the objects"""
        # Call the user function to create the initial objects
        initial_objects = self.initial_objects_func(self.rank, self.size, self.config)

        # Set owner_rank and insert into the object pool
        for obj_data in initial_objects:
            position = [obj_data['x'], obj_data['y'], obj_data['z']]
            owner_rank = self.domain_decomp.get_owner_rank(position)

            # Only add the objects owned by this rank
            if owner_rank == self.rank:
                obj = create_object(
                    obj_id=obj_data['id'],
                    obj_type=obj_data['type'],
                    position=position,
                    owner_rank=owner_rank,
                    float_props=obj_data.get('float_props', []),
                    size=obj_data.get('size', 0.0),  # object size
                    config=self.config  # pass config so the right dtype is used
                )
                self.rma_object_pool.add_object(obj)

    def _build_events(self):
        """
        Build the events (the O(delta) optimized version)

        Core pipeline:
        1. synchronize and fetch the set of changed objects
        2. test the conditions forcing a full rebuild (a sharp temperature change, say)
        3. save the event snapshot (reused by the incremental mode)
        4. call the builder (in full or incremental mode)

        Incremental mode requires:
        - changed_objects is not None
        - rebuild_single = True (telling the builder it may go incremental)
        - the builder itself decides from changed_objects whether to go full or incremental

        Full mode happens when:
        - changed_objects = None (a global state change)
        - or rebuild_single = False (single-object events are not rebuilt)

        [optimization] The changed_objects synchronization moved into the Allgather of _select_event
        so the result of the previous step is used directly here
        """
        # Step 0: clear the ghost events left by the previous step
        # Idea: the changed_objects of step N are cleaned before the events of step N+1 are built
        # Reason: the object data embedded in an event is stale and must go before the rebuild
        # Note: only needed with the incremental update on; a full rebuild leaves no ghosts
        # Events stolen in the previous rate stage now live on the thief; drop the SENT
        # husks so the victim's pool holds exactly what it still owns (as after a
        # predictive move). Invalidation of the moved events then follows the broadcast
        # change set below, on whichever rank hosts them.
        if self.runtime_load_balancer.enabled:
            self.rma_event_pool.purge_sent_events()

        if self.incremental_manager.enabled:
            deleted_objects = self.incremental_manager.get_deleted_objects()
            # [perf] Pool-level cleanup is only necessary with an event-moving LB present
            # (an event may be hosted by a rank that is not its owner, whose build path
            # cannot see the host object). With both off it is pure redundancy: the
            # valid/stale double filter of the single in-place path
            # (jit_mark_stale_single_events), or the wholesale replacement of a full
            # rebuild, already covers every invalidation.
            # [event-LB] With an event-moving LB on, every rank drops the events of the
            # objects that changed or vanished this step, from the broadcast change set:
            # a host rank never sees the owner's new/changed flags, so this is the only
            # place it can invalidate a foreign event. The owner rebuilds the events of its
            # changed objects on the in-place path, so retained foreign events stay valid.
            # Structure only: retained events still fall back to TODO unless the class
            # asked for incremental_rate.
            # [fix] The events of DELETED objects are always removed here, LB or not.
            # A pure deletion leaves changed_objects empty (mark_objects_deleted takes the
            # id out of it), so should_rebuild_single_obj_events() returns False and the
            # valid/stale filter of the in-place path never runs: the DONE event of the
            # vanished object stayed in the pool, got selected, and apply_changed_objects
            # re-created the object from the stale snapshot (the object was resurrected,
            # absorbed again, and the run never reached total rate zero). The cleanup is
            # O(removals) (swap-remove + rate delta) and deletion steps are rare.
            # Only the cleanup of CHANGED objects stays gated on an event-moving LB.
            stale_ids = set(deleted_objects)
            if self._ghost_cleanup_needed():
                stale_ids.update(self.incremental_manager.get_changed_objects())
            if len(stale_ids) > 0:
                stale_arr = np.array(list(stale_ids), dtype=np.int64)
                # Clear the ghost events in the single-object pool (JIT scan + swap-remove)
                self.rma_event_pool.remove_events_for_objects(stale_arr)

                if self.verbose and self.rank == 0:
                    print(f"Step {self.current_step}: Cleaned {len(stale_arr)} ghost events")
            if len(deleted_objects) > 0:
                # Clear the set either way, so nothing accumulates
                self.incremental_manager.clear_deleted_objects()

        # Step 2: decide the rebuild scope
        # [contract] The structural increment is always on: the structural reuse of single
        # events happens on the in-place path of the builder (driven by the object flags;
        # rebuild_single=False means the whole pool is kept as is). When a rebuild is due
        # but the in-place preconditions fail (first step / global change / physics rebuild /
        # event-moving LB / too many changes) the builder falls back to a full rebuild.
        rebuild_single = self.incremental_manager.should_rebuild_single_obj_events()
        rebuild_zero = self.incremental_manager.should_rebuild_zero_obj_events()
        changed_objects = None

        # The coin (migrated object tracking) fed the retired snapshot path; clear it to be safe
        self.incremental_manager.clear_migrated_obj_ids()
        migrated_obj_ids = None

        # [pair-inc] Decide whether the pair structural increment applies (else a full rebuild)
        # A full rebuild is forced by: the first step, a global state change (RCB/ObjectLB
        # repartition included), a stale or uninitialized ghost cache (which covers a change of
        # r_cut - the geometric premise 'the ghost region covers the cutoff' must hold)
        pair_changed_arr = None
        allow_pair_rate_keep = False
        if (self._pair_structure_enabled
                and self.current_step > 0
                and self._pair_changed_arr is not None
                and not self.incremental_manager.global_state_changed
                # The force flags are structural only (first step, repartition, a user
                # request); a physics change no longer sets them - it invalidates the
                # dependent rates and rewrites cached params in place (_invalidate_rates_for_physics)
                and not self.incremental_manager.force_rebuild_single
                and not self.incremental_manager.force_rebuild_zero
                and self.rma_object_pool._ghost_cache_initialized
                and not self.rma_object_pool._ghost_cache_dirty):
            pair_changed_arr = self._pair_changed_arr
                # A physics-forced rebuild was excluded above, so a structurally reused step
                # may let classes with incremental_rate=True keep their DONE rate
            allow_pair_rate_keep = True

        # [fix] Safety preconditions of the single-event in-place fast path: it must not cross
        # a global structural change (repartition -> global_state_changed) or a user-forced
        # rebuild. Runtime SENT stealing stays excluded (a SENT husk reset to
        # TODO would be double counted). Predictive (event-level) migration is allowed: the
        # host of a foreign event invalidates it from the broadcast change set in Step 0
        # above, and the builder keeps foreign events on the in-place path
        # (foreign_events_hosted below) instead of treating ownership as validity.
        # Event-moving levels (predictive and runtime) are handled alike: a moved event
        # stays with the rank that received it, the broadcast change set invalidates it
        # wherever it lives (Step 0), and the builder keeps foreign events on the
        # in-place path. No full rebuild is needed after a move.
        allow_single_inplace = (
            not self.incremental_manager.global_state_changed
            and not self.incremental_manager.force_rebuild_single
            and not self.incremental_manager.force_rebuild_zero)

        self.event_builder.build_all_events(
            self.rma_object_pool,
            self.rma_event_pool,
            changed_objects=changed_objects,  # always None now the snapshot path is retired
            rebuild_zero=rebuild_zero,
            rebuild_single=rebuild_single,
            current_step=self.current_step,  # [fix] pass the current step
            migrated_obj_ids=migrated_obj_ids,
            pair_changed_arr=pair_changed_arr,
            allow_pair_rate_keep=allow_pair_rate_keep,
            allow_single_inplace=allow_single_inplace,
            foreign_events_hosted=(self.predictive_rebalancer.enabled
                                   or self.runtime_load_balancer.enabled)
        )

        # Clear the object flags (the events have been built)
        self._clear_object_flags()

        # [fix] Clear changed_objects (the events have been rebuilt)
        self.incremental_manager.clear_changed_objects()

    def _clear_object_flags(self):
        """
        Clear the new and changed flags of the objects

        Called once event construction is done, so the flags cannot accumulate
        """
        # Does the object dtype carry the flag fields?
        if 'new' not in self.rma_object_pool.dtype.names:
            return  # an older dtype, nothing to do

        # [performance fix] Vectorized: the original looped over objects in Python and cost
        # tens of milliseconds per step with many objects (e.g. 1e4 idle sinks).
        # The semantics are unchanged: only the flags of active objects are cleared.
        pool = self.rma_object_pool
        for arr, n in ((pool.center_objects, pool.center_count),
                       (pool.boundary_objects, pool.boundary_count),
                       (pool.large_objects, pool.large_count)):
            if n > 0:
                active = arr['active'][:n]
                arr['new'][:n][active] = False
                arr['changed'][:n][active] = False

    def _compute_rates(self):
        """
        Evaluate every event rate (runtime load balancing included)

        Simplification: _compute_rates_with_event_registry() is called directly,
        since the event class system is the only path.

        [fix] Idle polling added:
        once this rank is done it marks itself idle and polls for events sent by busy ranks.
        """
        # Step 0: mark ourselves busy (the computation starts)
        self.runtime_load_balancer.mark_busy()

        # Update the current time (used by the temperature schedule)
        self.config['_current_time'] = self.current_time

        # Evaluate the rates through the event class system
        self._compute_rates_with_event_registry()

        # [fix] Mark ourselves idle and then poll for events
        # Scenario: this rank finishes first -> mark_idle -> a busy rank notices and sends work
        # We must keep polling until nothing new arrives
        self.runtime_load_balancer.mark_idle()

        # Receive and evaluate the events sent by other ranks until every stolen batch
        # has been delivered and evaluated. A rank sends only inside its own rate loop,
        # so once that loop is over its send count is final. Each rank then
        #   1. keeps receiving/evaluating, and waits until all of its own batches are ACKed;
        #   2. enters a non-blocking barrier and keeps receiving/evaluating until it completes.
        # When the barrier completes every rank has all its batches ACKed, i.e. received and
        # appended by the thief, which evaluates them right after receiving. No stolen event
        # can then be missing from the partial rates that the selection stage gathers.
        # (A bounded number of polls used to exit early: an event sent after the thief had
        # stopped polling was SENT on the victim and absent on the thief, so its rate was
        # lost for the step and the event reappeared later as a stale duplicate.)
        rlb = self.runtime_load_balancer
        if rlb.enabled and self.size > 1:
            barrier = None
            while True:
                self._compute_received_events()
                rlb.check_acks()
                if barrier is None:
                    if rlb.pending_acks == 0:
                        barrier = self.comm.Ibarrier()
                elif barrier.Test():
                    break
            # anything that arrived between the last poll and the barrier completion
            self._compute_received_events()

    def _compute_rates_with_event_registry(self):
        """
        Evaluate the rates through the event registry

        Two phases:
        Phase 0: JIT batch evaluation (rate_deps + rate_kernel, the fastest)
        Phase 1: scalar Python evaluation (rate(), for everything left)

        The intermediate NumPy vectorization layer (the rate_function batch path) was removed
        """
        computed_count = 0

        # JIT event types
        jit_types = set(self.event_registry.get_jit_events()) if self.jit_dispatcher else set()

        # Adapt the runtime LB check interval
        total_events = (self.rma_event_pool.count_zero +
                        self.rma_event_pool.count_single +
                        self.rma_event_pool.count_pair)
        self.runtime_load_balancer.update_check_interval(total_events)

        # Runtime LB: mark ourselves idle at once when this rank holds no event
        if total_events == 0:
            self.runtime_load_balancer.mark_idle()
            return

        # Walk the three event arrays
        for array_name, events_array, count in [
            ('zero', self.rma_event_pool.zero_obj_array, self.rma_event_pool.count_zero),
            ('single', self.rma_event_pool.single_obj_array, self.rma_event_pool.count_single),
            ('pair', self.rma_event_pool.pair_obj_array, self.rma_event_pool.count_pair),
        ]:
            if count == 0:
                continue

            valid_events = events_array[:count]
            category_rate_delta = 0.0

            # Phase 0: JIT events (batched, the fastest)
            if jit_types and self.jit_dispatcher:
                n_jit, jit_rate_delta = self._compute_rates_jit_batch(
                    events_array, count, array_name, jit_types)
                computed_count += n_jit
                category_rate_delta += jit_rate_delta

            # Phase 1: scalar Python evaluation (every remaining non-JIT event)
            for i in range(count):
                event = valid_events[i]
                if event['status'] != 0:  # skip what is done (the JIT phase handled it)
                    continue

                # Get the event class
                event_type_str = self._resolve_event_type_name(event)
                event_class = self.event_registry.get(event_type_str)
                if event_class is None:
                    continue

                # Prepare the parameters
                params = event['params'].tolist()
                objs = self._get_objects_for_event(event, array_name)

                # Call the scalar rate function
                t_start = time.perf_counter()
                rate = event_class.rate(objs, dict(zip(event_class.params, params)), self.config)
                t_elapsed = time.perf_counter() - t_start

                # Write back
                # [fix] NaN/Inf guard: max(nan, 0.0) keeps the nan, which poisons the cumsum
                # so the selection stage finds no winner and the run stops silently
                rate = float(rate)
                if not np.isfinite(rate):
                    self._warn_once(
                        f"nonfinite-rate:{event_type_str}",
                        f"event '{event_type_str}' returned non-finite rate "
                        f"({rate}); clamped to 0. Check the rate function "
                        f"(e.g. exp() overflow).")
                    rate = 0.0
                rate = max(rate, 0.0)
                events_array[i]['rate'] = rate
                events_array[i]['status'] = 2
                category_rate_delta += float(rate)

                self.adaptive_weight_tracker.record_event_computation(event_type_str, t_elapsed)
                computed_count += 1

                # Load balancing check
                self.runtime_load_balancer.redistribute_if_needed(self.rma_event_pool, computed_count)

            self.rma_event_pool.add_rate_sum_delta(array_name, category_rate_delta)

    def _build_rate_dependency_tables(self):
        """Map physics parameter / field names to the event classes whose RATE uses them.

        Principle: the structure of the event pool (which objects carry which events)
        depends only on the objects and the geometry; a physics parameter or field only
        enters the rates. A physics change therefore invalidates rates, never structure.

        Three sources of dependency, all static (known once the event classes are
        registered):
          1. rate_deps.physics / rate_deps.fields of a JIT class: the kernel reads the
             live physics values at rate time, so a DONE rate must be dropped to TODO;
          2. a name in cls.params that resolves from the physics module (scalar rate()):
             the value is cached in event['params'] at build time, so the cached column
             must be rewritten and the rate dropped to TODO;
          3. a scalar class without rate_deps and without params that keeps its rates
             (incremental_rate=True): its rate() can only be reading the physics module
             directly, so it depends on every parameter and field. A scalar class that
             declares params is taken at its word: it depends on those (case 2) only.
        A scalar class without rate_deps and without incremental_rate recomputes its
        rate every step and needs no entry (its cached params column still does, case 2).
        """
        self._rate_deps_by_param: Dict[str, List[int]] = {}
        self._rate_deps_by_field: Dict[str, List[int]] = {}
        self._rate_deps_all: List[int] = []
        self._scalar_param_cols: Dict[str, List[Tuple[int, int]]] = {}
        self._all_event_type_ids: List[int] = []
        self._rate_deps_known_params: set = set()

        if self.physics is None:
            return
        name_to_int = self.config.get('_event_name_to_int', {}) or {}
        physics_params = set(self.physics.get_param_names())
        self._rate_deps_known_params = set(physics_params)
        props_mapping = (self.config.get('_props_mapping', {}) or {}).get('float_props', {}) or {}
        events_cfg = self.config.get('events', {}) or {}

        for event_name, cls in self.event_registry.get_all_events().items():
            gid = name_to_int.get(event_name)
            if gid is None:
                continue
            self._all_event_type_ids.append(int(gid))
            rate_deps = getattr(cls, 'rate_deps', None)
            incremental = bool(getattr(cls, 'incremental_rate', False))
            if rate_deps is not None:
                for p in (getattr(rate_deps, 'physics', None) or []):
                    self._rate_deps_by_param.setdefault(str(p), []).append(int(gid))
                for f in (getattr(rate_deps, 'fields', None) or []):
                    self._rate_deps_by_field.setdefault(str(f), []).append(int(gid))
            elif incremental and not (getattr(cls, 'params', None) or []):
                self._rate_deps_all.append(int(gid))

            # case 2: params resolved from the physics module and cached in the event.
            # A name that is an object property of one of the class's types, or an entry
            # of the event's own config block, resolves from there instead (get_params
            # lookup order), so it is not a physics dependency.
            obj_types = []
            for attr in ('object_types',):
                obj_types.extend(getattr(cls, attr, None) or [])
            for pair in (getattr(cls, 'type_pairs', None) or []):
                obj_types.extend(pair)
            own_props = set()
            for t in obj_types:
                own_props.update((props_mapping.get(str(t), {}) or {}).keys())
            event_block = events_cfg.get(event_name, {}) if isinstance(events_cfg, dict) else {}
            if not isinstance(event_block, dict):
                event_block = {}
            for col, p in enumerate(getattr(cls, 'params', None) or []):
                p = str(p)
                if p in physics_params and p not in own_props and p not in event_block:
                    self._scalar_param_cols.setdefault(p, []).append((int(gid), col))
                    self._rate_deps_by_param.setdefault(p, []).append(int(gid))

    def _invalidate_rates_for_physics(self, param_names, field_names,
                                      everything: bool = False) -> bool:
        """Drop the rates that depend on the changed physics; touch no structure.

        Args:
            param_names: names of the parameters that changed
            field_names: names of the fields that changed
            everything: the scope is unknown (a global update_func ran), so every class
                        is treated as dependent

        Returns:
            whether any rate was invalidated or any cached param column refreshed
        """
        if self.physics is None:
            return False
        param_names = [p for p in param_names if p]
        field_names = [f for f in field_names if f]
        # a parameter defined after the tables were built (set_param_in_event may define
        # one on the fly): rebuild the tables once so a cls.params entry naming it is seen
        if any(p not in self._rate_deps_known_params for p in param_names):
            self._build_rate_dependency_tables()
        gids = set()
        if everything:
            gids.update(self._all_event_type_ids)
            param_names = self.physics.get_param_names()
        else:
            for p in param_names:
                gids.update(self._rate_deps_by_param.get(p, ()))
            for f in field_names:
                gids.update(self._rate_deps_by_field.get(f, ()))
            if param_names or field_names:
                gids.update(self._rate_deps_all)

        refresh = []
        for p in param_names:
            cols = self._scalar_param_cols.get(p)
            if cols:
                value = self.physics.get_param(p)
                refresh.extend((gid, col, value) for gid, col in cols)

        if not gids and not refresh:
            return False
        n_reset = 0
        if refresh:
            self.rma_event_pool.write_param_column_by_type(refresh)
        if gids:
            n_reset = self.rma_event_pool.mark_rates_todo_by_type(
                np.array(sorted(gids), dtype=np.int32))
        self._n_rate_invalidations += 1
        if self.verbose and self.rank == 0:
            print(f"Step {self.current_step}: physics change -> {len(gids)} dependent event "
                  f"classes, {n_reset} rates back to TODO, {len(refresh)} cached param "
                  f"columns refreshed (no structural rebuild)")
        return True

    @staticmethod
    def _flag_indices(flags: np.ndarray) -> List[int]:
        """Indices of the set bits of a uint64[4] flag array (256 slots)."""
        out = []
        if flags is None:
            return out
        for word_idx, word in enumerate(np.asarray(flags, dtype=np.uint64)):
            w = int(word)
            bit = 0
            while w:
                if w & 1:
                    out.append(word_idx * 64 + bit)
                w >>= 1
                bit += 1
        return out

    def _ghost_cleanup_needed(self) -> bool:
        """Whether the pool-level ghost event cleanup is necessary.

        [perf] With an event-moving LB present (predictive migration or runtime SENT
        stealing) an event referring to a changed object may be hosted by any rank, whose
        build path cannot see the host object, so the pool-level cleanup is the safety net.
        With both off the invariant 'this pool is exactly the events of this rank's objects'
        holds, and either the valid/stale filter of the single in-place path or the wholesale
        replacement of a full rebuild already covers every invalidation of CHANGED objects,
        so that part is redundant. This gate does NOT cover deleted objects: their events
        are removed unconditionally in _build_events step 0 (a pure deletion triggers no
        single-event rebuild at all, see the [fix] note there).
        """
        return (self.predictive_rebalancer.enabled
                or self.runtime_load_balancer.enabled)

    def _warn_once(self, key: str, message: str):
        """Print a warning only once per key."""
        if not hasattr(self, '_warned_keys'):
            self._warned_keys = set()
        if key not in self._warned_keys:
            self._warned_keys.add(key)
            print(f"[Rank {self.rank}] Warning: {message}")

    def _compute_received_events(self):
        """
        [fix] Evaluate the events received from other ranks

        Scenario: this rank finishes first -> mark_idle -> a busy rank sends events over
        This method receives them and evaluates their rates so they count towards our total.
        """
        # Receive everything pending first
        self.runtime_load_balancer.check_incoming_tasks(self.rma_event_pool)

        # Evaluate every event still TODO, not only those received in this call: events
        # received inside the main rate loop (whose range was fixed when it started) are
        # appended beyond that range and would otherwise stay TODO with rate 0.
        for array_name in ['zero', 'single', 'pair']:
            if array_name == 'zero':
                events_array = self.rma_event_pool.zero_obj_array
                count = self.rma_event_pool.count_zero
            elif array_name == 'single':
                events_array = self.rma_event_pool.single_obj_array
                count = self.rma_event_pool.count_single
            else:
                events_array = self.rma_event_pool.pair_obj_array
                count = self.rma_event_pool.count_pair

            category_rate_delta = 0.0
            if count == 0:
                continue
            todo_idx = np.flatnonzero(events_array[:count]['status'] == 0)
            for i in todo_idx:
                event = events_array[i]

                event_type_str = self._resolve_event_type_name(event)
                event_class = self.event_registry.get(event_type_str)
                if event_class is None:
                    continue

                params = event['params'].tolist()
                objs = self._get_objects_for_event(event, array_name)

                rate = event_class.rate(objs, dict(zip(event_class.params, params)), self.config)
                # [fix] NaN/Inf guard: max(nan, 0.0) keeps the nan, which poisons the cumsum
                # so the selection stage finds no winner and the run stops silently
                rate = float(rate)
                if not np.isfinite(rate):
                    self._warn_once(
                        f"nonfinite-rate:{event_type_str}",
                        f"event '{event_type_str}' returned non-finite rate "
                        f"({rate}); clamped to 0. Check the rate function "
                        f"(e.g. exp() overflow).")
                    rate = 0.0
                rate = max(rate, 0.0)
                events_array[i]['rate'] = rate
                events_array[i]['status'] = 2
                category_rate_delta += float(rate)

            self.rma_event_pool.add_rate_sum_delta(array_name, category_rate_delta)

    def _get_objects_for_event(self, event: np.void, category: str) -> list:
        """
        Get the object data of an event (self-contained mode only)

        Args:
            event: the event record
            category: event class ('zero', 'single', 'pair')

        Returns:
            the list of objects (as dicts)
        """
        if category == 'zero':
            return []

        # Only the self-contained mode is supported
        if category == 'single':
            obj_data = event['objects'][0]
            return [self._object_record_to_user_dict(obj_data)]
        elif category == 'pair':
            obj1_data = event['objects'][0]
            obj2_data = event['objects'][1]
            return [
                self._object_record_to_user_dict(obj1_data),
                self._object_record_to_user_dict(obj2_data)
            ]

        return []

    def _compute_rates_jit_batch(self, events_array, count, array_name, jit_types):
        """
        JIT batch rate evaluation

        Events are grouped by type, and for each group of JIT events:
        1. extract contiguous float_props and type_ids
        2. pre-interpolate the physics fields
        3. call JITRateDispatcher.compute_rates()
        4. write the rates and statuses back
        """
        if count == 0 or not self.jit_dispatcher:
            return 0, 0.0

        valid_events = events_array[:count]

        # Select the pending JIT events
        todo_mask = valid_events['status'] == 0
        if not np.any(todo_mask):
            return 0, 0.0

        todo_indices = np.nonzero(todo_mask)[0]
        use_event_type_id = 'event_type_id' in valid_events.dtype.names
        if use_event_type_id:
            todo_type_ids = valid_events['event_type_id'][todo_indices].astype(np.int32)
            unique_type_ids = np.unique(todo_type_ids)
        else:
            todo_types = valid_events['type'][todo_indices]
            unique_types = np.unique(todo_types)

        computed = 0
        category_rate_delta = 0.0

        iterable = unique_type_ids if use_event_type_id else unique_types
        for event_type in iterable:
            if use_event_type_id:
                event_type_id = int(event_type)
                event_type_str = self.config.get('_event_int_to_name', {}).get(event_type_id)
                if event_type_str is None:
                    continue
            else:
                event_type_id = None
                event_type_str = str(event_type).strip()
            if event_type_str not in jit_types:
                continue
            if not self.jit_dispatcher.has_event(event_type_str):
                continue

            if use_event_type_id:
                type_mask = (todo_type_ids == event_type_id)
            else:
                type_mask = (todo_types == event_type)
            type_indices = todo_indices[type_mask]
            n_events = len(type_indices)
            if n_events == 0:
                continue

            kind = self.jit_dispatcher.get_kind(event_type_str)
            entry = self.jit_dispatcher.registry[event_type_str]
            deps = entry['deps']

            # Build physics_vals
            physics_vals = np.empty(len(deps.physics), dtype=np.float64)
            for k, pname in enumerate(deps.physics):
                from .event_class import get_physics_param
                physics_vals[k] = float(get_physics_param(self.config, pname, default=0.0))

            # Build field_vals (pre-interpolated)
            n_fields = len(deps.fields)
            batch_events = valid_events[type_indices]

            if n_fields > 0 and kind == 'zero':
                # Field values of zero-object events
                # per_cell mode: VectorizedZeroEventBuilder already stored them in params
                # global mode: there is no position, so the field values are 0
                event_class_for_field = self.event_registry.get(event_type_str)
                event_field_deps = getattr(event_class_for_field, 'field_deps', [])
                spatial_mode = getattr(event_class_for_field, 'spatial_mode', 'global')

                field_vals = np.zeros((n_events, n_fields), dtype=np.float64)
                if spatial_mode == 'per_cell' and event_field_deps:
                    # Read the field values out of params by name
                    for k, fname in enumerate(deps.fields):
                        if fname in event_field_deps:
                            src_idx = event_field_deps.index(fname)
                            field_vals[:, k] = batch_events['params'][:, src_idx]
            elif n_fields > 0 and 'objects' in events_array.dtype.names:
                field_vals = np.zeros((n_events, n_fields), dtype=np.float64)
                obj_data = batch_events['objects'][:, 0]
                x = obj_data['x']
                y = obj_data['y']
                z = obj_data['z']
                from .event_class import interpolate_field_batch
                for k, fname in enumerate(deps.fields):
                    fv = interpolate_field_batch(self.config, fname, x, y, z)
                    if fv is not None:
                        field_vals[:, k] = fv
            else:
                field_vals = np.empty((n_events, max(n_fields, 0)), dtype=np.float64)

            t_start = time.perf_counter()

            if kind == 'pair':
                obj1 = batch_events['objects'][:, 0]
                obj2 = batch_events['objects'][:, 1]
                o1_props = obj1['float_props'].astype(np.float64)
                o2_props = obj2['float_props'].astype(np.float64)

                # Use the type_id field directly
                o1_tids = obj1['type_id'].astype(np.int32)
                o2_tids = obj2['type_id'].astype(np.int32)

                distances = batch_events['params'][:, 0].astype(np.float64)

                rates = self.jit_dispatcher.compute_rates(
                    event_type_str,
                    o1_props=o1_props, o2_props=o2_props,
                    o1_type_ids=o1_tids, o2_type_ids=o2_tids,
                    distances=distances, field_vals=field_vals,
                    physics_vals=physics_vals)

            elif kind == 'single':
                obj1 = batch_events['objects'][:, 0]
                o1_props = obj1['float_props'].astype(np.float64)
                # Use the type_id field directly
                o1_tids = obj1['type_id'].astype(np.int32)

                rates = self.jit_dispatcher.compute_rates(
                    event_type_str,
                    o1_props=o1_props, o1_type_ids=o1_tids,
                    field_vals=field_vals, physics_vals=physics_vals)

            else:  # zero
                rates = self.jit_dispatcher.compute_rates(
                    event_type_str,
                    field_vals=field_vals, physics_vals=physics_vals,
                    n_events=n_events)

            t_elapsed = time.perf_counter() - t_start

            # Write back: a negative rate is clamped to 0 so nothing downstream keeps it
            # [fix] NaN/Inf guard: np.maximum propagates NaN
            nonfinite = ~np.isfinite(rates)
            if np.any(nonfinite):
                self._warn_once(
                    f"nonfinite-rate:{event_type_str}",
                    f"JIT kernel for '{event_type_str}' returned "
                    f"{int(np.sum(nonfinite))} non-finite rates; clamped to 0.")
                rates = np.where(nonfinite, 0.0, rates)
            rates = np.maximum(rates, 0.0)
            events_array['rate'][type_indices] = rates
            events_array['status'][type_indices] = 2
            category_rate_delta += float(np.sum(rates, dtype=np.float64))

            self.adaptive_weight_tracker.record_batch_computation(
                event_type_str, n_events, t_elapsed)
            computed += n_events

        return computed, category_rate_delta


    def _get_total_rate(self) -> float:
        """Get the total rate (local events and stolen work included)"""
        # [diagnostic] Detect drift between the rate mirror and the pool contents (off by
        # default; set PARAOKMC_RATE_DRIFT_CHECK=1 to enable; O(N) per step, debugging only)
        import os as _os
        if _os.environ.get('PARAOKMC_RATE_DRIFT_CHECK'):
            ep = self.rma_event_pool
            for cat, arr, cnt, mirror in (
                    ('zero', ep.zero_obj_array, ep.count_zero, ep.rate_sum_zero),
                    ('single', ep.single_obj_array, ep.count_single, ep.rate_sum_single),
                    ('pair', ep.pair_obj_array, ep.count_pair, ep.rate_sum_pair)):
                actual = ep._sum_valid_rates(arr[:cnt])
                if abs(actual - mirror) > 1e-6 * max(1.0, abs(actual)):
                    print(f"[DRIFT] step={self.current_step} rank={self.rank} "
                          f"cat={cat} mirror={mirror:.6e} actual={actual:.6e} "
                          f"count={cnt}", flush=True)
        return self.rma_event_pool.get_total_rate()

    def _select_event(self, local_total_rate: float) -> Tuple[int, str, int]:
        """
        Select an event (globally)

        [optimization] Two communications:
        - communication 1: Allgather(rate + random)
          - rank 0 sends its random number as well, the others send 0
          - every rank sees the random value and computes winner_rank locally
          - the former Bcast(random) is gone
        - communication 2: Bcast(changed_objects) inside _execute_event

        Pipeline:
        1. Allgather the total rate of every rank plus the random number of rank 0
        2. every rank computes winner_rank locally (no further communication)
        3. the winner picks the concrete event in its own pool
        """
        # [optimization] One merged Allgather: rate + random
        # rank 0 draws the random number, the others send 0
        # The globally consistent generator is used (state=1 marks event selection)
        if self.rank == 0:
            random_val = self.rng.random_for_event_selection()
        else:
            random_val = 0.0

        # Build the array holding rate and random
        local_data = np.array([local_total_rate, random_val], dtype=np.float64)
        all_data = np.empty((self.size, 2), dtype=np.float64)

        self.comm.Allgather([local_data, MPI.DOUBLE], [all_data, MPI.DOUBLE])

        # Extract the rates and the random number
        all_rates_arr = all_data[:, 0]
        random_from_rank0 = all_data[0, 1]  # the random number of rank 0

        global_total_rate = np.sum(all_rates_arr)

        # [fix] Guard against a non-finite total rate: rates are clamped when written back,
        # so this only catches the residue that would let a NaN break the winner test silently
        if not np.isfinite(global_total_rate):
            self._warn_once(
                'nonfinite-total-rate',
                f"global total rate is non-finite ({global_total_rate}); "
                f"treating as 0 and stopping event selection this step.")
            return -1, 'none', -1, 0.0

        if global_total_rate <= 0:
            return -1, 'none', -1, 0.0

        # Scale the random number to [0, global_total_rate)
        r = random_from_rank0 * global_total_rate

        # Determine the winner rank (computed locally, identically on every rank)
        current_sum = 0.0
        winner_rank = -1
        for i in range(self.size):
            current_sum += all_rates_arr[i]
            if r < current_sum:
                winner_rank = i
                break

        # If we are the winner, pick the concrete event
        event_category = 'none'
        local_idx = -1

        if self.rank == winner_rank:
            # Subtract the rates of the earlier ranks to get the local target rate
            target_rate = r - (current_sum - all_rates_arr[self.rank])

            # Search the local pool
            # Order: zero -> single -> pair
            current_local_sum = 0.0
            found = False

            # Check the zero-object events
            if not found and self.rma_event_pool.count_zero > 0:
                # Vectorized search: build the prefix sum
                # Note: only events with status=2 count
                zero_events = self.rma_event_pool.zero_obj_array[:self.rma_event_pool.count_zero]
                valid_mask = zero_events['status'] == 2
                if np.any(valid_mask):
                    rates = zero_events['rate']
                    # Detect and filter the negative rates
                    negative_mask = (rates < 0) & valid_mask
                    if np.any(negative_mask):
                        neg_count = np.sum(negative_mask)
                        if self.rank == winner_rank:
                            print(f"[Warning] Step {self.current_step}: {neg_count} zero events with negative rates detected")
                    # Zero the rate of invalid and negative-rate events
                    valid_rates = np.where(valid_mask & (rates >= 0), rates, 0.0)
                    cumsum = np.cumsum(valid_rates)

                    if target_rate < cumsum[-1]:
                        # Found
                        idx = np.searchsorted(cumsum, target_rate)
                        event_category = 'zero'
                        local_idx = idx
                        found = True
                    else:
                        current_local_sum += cumsum[-1]
                        target_rate -= cumsum[-1]

            # Check the single-object events
            if not found and self.rma_event_pool.count_single > 0:
                single_events = self.rma_event_pool.single_obj_array[:self.rma_event_pool.count_single]
                valid_mask = single_events['status'] == 2
                if np.any(valid_mask):
                    rates = single_events['rate']
                    # Detect and filter the negative rates
                    negative_mask = (rates < 0) & valid_mask
                    if np.any(negative_mask):
                        neg_count = np.sum(negative_mask)
                        if self.rank == winner_rank:
                            print(f"[Warning] Step {self.current_step}: {neg_count} single events with negative rates detected")
                    # Zero the rate of invalid and negative-rate events
                    valid_rates = np.where(valid_mask & (rates >= 0), rates, 0.0)
                    cumsum = np.cumsum(valid_rates)

                    if target_rate < cumsum[-1]:
                        idx = np.searchsorted(cumsum, target_rate)
                        event_category = 'single'
                        local_idx = idx
                        found = True
                    else:
                        current_local_sum += cumsum[-1]
                        target_rate -= cumsum[-1]

            # Check the pair events
            if not found and self.rma_event_pool.count_pair > 0:
                pair_events = self.rma_event_pool.pair_obj_array[:self.rma_event_pool.count_pair]
                valid_mask = pair_events['status'] == 2
                if np.any(valid_mask):
                    rates = pair_events['rate']
                    # Detect and filter the negative rates
                    negative_mask = (rates < 0) & valid_mask
                    if np.any(negative_mask):
                        neg_count = np.sum(negative_mask)
                        if self.rank == winner_rank:
                            print(f"[Warning] Step {self.current_step}: {neg_count} pair events with negative rates detected")
                    # Zero the rate of invalid and negative-rate events
                    valid_rates = np.where(valid_mask & (rates >= 0), rates, 0.0)
                    cumsum = np.cumsum(valid_rates)

                    # When rounding pushes target_rate just past cumsum[-1] this branch is
                    # skipped and the fallback below takes the last valid event (no overrun)
                    if target_rate < cumsum[-1]:
                        idx = np.searchsorted(cumsum, target_rate)
                        event_category = 'pair'
                        local_idx = idx
                        found = True

            # [fix] Nothing found after all three classes (an extreme rounding case):
            # take the last valid event as a fallback rather than ending the run wrongly
            if not found:
                # Look for the last valid event in pair, then single, then zero
                if self.rma_event_pool.count_pair > 0:
                    valid_mask = self.rma_event_pool.pair_obj_array[:self.rma_event_pool.count_pair]['status'] == 2
                    if np.any(valid_mask):
                        event_category = 'pair'
                        local_idx = np.where(valid_mask)[0][-1]  # the last valid event
                        found = True

                if not found and self.rma_event_pool.count_single > 0:
                    valid_mask = self.rma_event_pool.single_obj_array[:self.rma_event_pool.count_single]['status'] == 2
                    if np.any(valid_mask):
                        event_category = 'single'
                        local_idx = np.where(valid_mask)[0][-1]
                        found = True

                if not found and self.rma_event_pool.count_zero > 0:
                    valid_mask = self.rma_event_pool.zero_obj_array[:self.rma_event_pool.count_zero]['status'] == 2
                    if np.any(valid_mask):
                        event_category = 'zero'
                        local_idx = np.where(valid_mask)[0][-1]
                        found = True

        return winner_rank, event_category, local_idx, global_total_rate

    def _build_complete_objects(self, changed_objects: List[Dict],
                                  objs_data: List[np.ndarray]) -> List[Dict]:
        """
        Build the complete objects for the broadcast

        Design principle: always broadcast complete objects so no data is lost
        - the user's execute_func may return only the changed fields (x, y, z, ...)
        - every property is copied from original_obj and then the user's changes applied
        - the receiver simply replaces the object, with no merge logic

        Args:
            changed_objects: the changed objects returned by execute_func (possibly partial)
            objs_data: the original objects of the event (with every property)

        Returns:
            the list of complete objects (each holding every field)
        """
        if not changed_objects:
            return changed_objects

        # Map object ID -> original record
        obj_id_to_data = {}
        for obj in objs_data:
            obj_id_to_data[int(obj['id'])] = obj

        # Build the list of complete objects
        complete_objects = []
        for obj_diff in changed_objects:
            obj_id = obj_diff['id']

            # [fix] Deletion: both the documented 'deleted': True and 'active': False work
            # The EventBase.execute() documentation and the bundled DiffusionCapture /
            # Annihilation classes use 'deleted': True - only active was honoured before,
            is_deleted = obj_diff.get('deleted', False) or not obj_diff.get('active', True)

            # A new object: the user must supply everything, so use it as is
            if obj_diff.get('new', False):
                if is_deleted:
                    # Created and deleted inside one event: it never existed, drop it
                    continue
                # [fix] Assign a unique ID automatically
                # Fix: handle every invalid ID (<= 0), not just -1
                # Fix: make sure IDs start at 1 (never 0)
                # [fix] Layout: [source:1=bit62][birth_rank:14][persistent_counter:48]
                # bit 62 separates runtime objects from initial-condition ones (the IC uses
                # (rank<<48)|counter, whose bit 62 is 0); the counter increases across steps,
                # removing the wrap-around and the deterministic clash of step<<16 over the IC range
                if obj_diff.get('id', -1) <= 0:
                    self._new_obj_local_counter += 1
                    obj_diff['id'] = (
                        (1 << 62) |
                        ((self.rank & 0x3FFF) << 48) |
                        (self._new_obj_local_counter & 0xFFFFFFFFFFFF)
                    )
                complete_objects.append(obj_diff)
                continue

            # Deletion: active = False
            # [pair-inc] Carry the coordinates before the deletion: the old-position side needs them
            # The record also carries the complete pre-deletion object (type, coordinates,
            # size, properties): the receivers only use the id to delete, but observers
            # (post-processor event hooks) need to know what was deleted. The message
            # record has a fixed size, so this costs no bandwidth.
            if is_deleted:
                deletion = {'id': obj_id, 'active': False}
                original_obj = obj_id_to_data.get(obj_id)
                if original_obj is not None:
                    deletion['type'] = self._object_type_name(original_obj)
                    deletion['x'] = float(original_obj['x'])
                    deletion['y'] = float(original_obj['y'])
                    deletion['z'] = float(original_obj['z'])
                    deletion['old_x'] = float(original_obj['x'])
                    deletion['old_y'] = float(original_obj['y'])
                    deletion['old_z'] = float(original_obj['z'])
                    deletion['old_valid'] = True
                    if isinstance(original_obj, dict):
                        if 'float_props' in original_obj:
                            deletion['float_props'] = list(original_obj['float_props'])
                        if 'size' in original_obj:
                            deletion['size'] = float(original_obj['size'])
                    else:
                        if 'float_props' in original_obj.dtype.names:
                            deletion['float_props'] = original_obj['float_props'].tolist()
                        if 'size' in original_obj.dtype.names:
                            deletion['size'] = float(original_obj['size'])
                complete_objects.append(deletion)
                continue

            # Modification: build a complete copy of the original and apply the changes
            if obj_id not in obj_id_to_data:
                # The original is missing from objs_data (an edge case): leave it alone
                complete_objects.append(obj_diff)
                continue

            original_obj = obj_id_to_data[obj_id]

            # Build the complete object from original_obj
            complete_obj = {
                'id': obj_id,
                'type': self._object_type_name(original_obj),
                'x': float(original_obj['x']),
                'y': float(original_obj['y']),
                'z': float(original_obj['z']),
                # [pair-inc] Coordinates before the change (the old-position side):
                # original_obj is the self-contained snapshot, i.e. the pre-execution state
                'old_x': float(original_obj['x']),
                'old_y': float(original_obj['y']),
                'old_z': float(original_obj['z']),
                'old_valid': True,
            }

            # Object type (used by the property mapping)
            obj_type = complete_obj['type']

            # Copy every property field
            if isinstance(original_obj, dict):
                if 'float_props' in original_obj:
                    complete_obj['float_props'] = list(original_obj['float_props'])
                if 'size' in original_obj:
                    complete_obj['size'] = float(original_obj['size'])
            else:
                if 'float_props' in original_obj.dtype.names:
                    complete_obj['float_props'] = original_obj['float_props'].tolist()

                if 'size' in original_obj.dtype.names:
                    complete_obj['size'] = float(original_obj['size'])

            # Apply the user's changes (overwriting by name, not merging by index)
            # Fetch the property mapping
            props_mapping = self.config.get('_props_mapping', {})
            float_mapping = props_mapping.get('float_props', {}).get(obj_type, {})

            for key, value in obj_diff.items():
                if key == 'id':
                    continue  # the id must not change

                # Is this a named property ('radius', 'n', 'm', ...)?
                if key in float_mapping:
                    # Map the name onto the right float_props index
                    idx = float_mapping[key]
                    if 'float_props' in complete_obj and idx < len(complete_obj['float_props']):
                        complete_obj['float_props'][idx] = float(value)
                elif key == 'float_props':
                    # Overwrite the whole float_props array (the user supplied it in full)
                    if value is not None and 'float_props' in complete_obj:
                        for i, v in enumerate(value):
                            if i < len(complete_obj['float_props']):
                                complete_obj['float_props'][i] = v
                else:
                    # Any other field (x, y, z, type, size, ...): overwrite it directly
                    complete_obj[key] = value

            complete_objects.append(complete_obj)

        return complete_objects

    def _execute_event(self, winner_rank: int, event_category: str, local_idx: int,
                       total_rate: float) -> Tuple[float, bool]:
        """
        Execute the event (with the unified broadcast)

        Removes the risk of a physics update deadlock:
        - the winner rank decides everything: dt and the physics update flags
        - one broadcast carries all of it
        - every rank acts on the same decision

        Pipeline:
        1. the winner rank executes the event and produces changed_objects
        2. the winner rank computes dt and the physics update flags
        3. the winner rank broadcasts everything to every rank
        4. every rank updates its object pool and the physics module

        Args:
            winner_rank: the winning rank
            event_category: event class ('zero', 'single', 'pair')
            local_idx: index of the event inside the local array
            total_rate: the total rate (used to compute dt)

        Returns:
            (dt, physics_changed)
            - dt: the time step
            - physics_changed: whether a physics change invalidated dependent rates
              (rates -> TODO, cached params refreshed; the structure is never rebuilt)
        """
        # Step 1: the winner rank executes the event
        changed_objects = None
        dt = 0.0
        # [fix] The extended flags live in numpy arrays (256 parameters/fields)
        param_flags = np.zeros(4, dtype=np.uint64)
        field_flags = np.zeros(4, dtype=np.uint64)
        global_flag = False
        # Physics changes produced by the execution
        physics_param_changes = []
        physics_field_deltas = []

        if self.rank == winner_rank:
            # Get the event
            event = None
            if event_category == 'zero':
                event = self.rma_event_pool.zero_obj_array[local_idx]
            elif event_category == 'single':
                event = self.rma_event_pool.single_obj_array[local_idx]
            elif event_category == 'pair':
                event = self.rma_event_pool.pair_obj_array[local_idx]

            # [fix] Defence: we won the draw but the category is invalid (phantom rate mass
            # from mirror residue drew us while no DONE event exists locally) -> run a no-op
            # step with empty changes. _select_event must not return -1 unilaterally: the
            # winner would leave the loop while the others wait for its broadcast (a deadlock)
            if event is None:
                self._warn_once(
                    'phantom-winner',
                    f"selected as winner but category='{event_category}' has "
                    f"no executable event (likely rate-mirror residue); "
                    f"executing a no-op step.")

            # Get the participating objects
            # Self-contained mode: the object data is read straight from the event
            # A zero-object event has none (the obj_ids[0] of a per_cell event is a cell_id)
            objs_data = []
            if event is not None and event_category != 'zero':
                # [fix] The empty-slot sentinel is -1 and ID=0 is a legal object ID (a user IC
                # may start at 0); the old '> 0' test silently skipped events touching ID 0
                num_objs = np.sum(event['obj_ids'] >= 0)
                for k in range(num_objs):
                    obj = event['objects'][k]
                    # Defensive check: the object must be valid and active
                    if obj['id'] >= 0 and obj['active']:
                        objs_data.append(self._object_record_to_user_dict(obj))
                    else:
                        # A ghost event: the object was deleted or is invalid
                        # obj_id < 0 is always reported, because it should never happen
                        if self.verbose or obj['id'] < 0:
                            print(f"Rank {self.rank} Step {self.current_step}: "
                                  f"Ghost event detected (obj_id={obj['id']}, active={obj['active']}), "
                                  f"category={event_category}, obj_index={k}/{num_objs}, "
                                  f"event_type={self._resolve_event_type_name(event)}, "
                                  f"event_obj_ids={event['obj_ids'][:3]}")
                        break

            # Are there enough valid objects?
            # - zero-object events: none needed
            # - single-object events: at least 1
            # - pair events: at least 2
            skip_event = event is None
            if event_category == 'single' and len(objs_data) < 1:
                skip_event = True
            elif event_category == 'pair' and len(objs_data) < 2:
                skip_event = True

            if skip_event:
                # Return empty changes
                changed_objects = []
                if self.verbose:
                    print(f"Rank {self.rank} Step {self.current_step}: "
                          f"Skipping ghost event (insufficient valid objects: {len(objs_data)} for {event_category})")
            else:
                # Open the physics change collection context
                if self.physics is not None:
                    self.physics.begin_event_execution()

                # Run the user's execute function
                # execute_func(event, objs, config) -> list[dict] | ExecuteResult
                result = self.execute_event_func(event, objs_data, self.config)

                # Two return formats are supported
                # [fix] The .changed/.new/.deleted the old code tested for do not exist on
                # ExecuteResult (it only has _changes/to_list/__iter__), so that branch never fired
                if isinstance(result, ExecuteResult):
                    changed_objects = result.to_list()
                elif hasattr(result, 'to_list'):
                    # A duck-typed result collector
                    changed_objects = result.to_list()
                else:
                    # The traditional list[dict] format
                    changed_objects = result

                # Close the collection and take the change list
                if self.physics is not None:
                    physics_param_changes, physics_field_deltas = self.physics.end_event_execution()

                # Build the complete objects for the broadcast
                # The user may return only the changed fields, so the rest is filled from the original
                # and the receiver can simply replace the object, with no merge logic
                changed_objects = self._build_complete_objects(changed_objects, objs_data)


            # Compute the time step (the winner rank does it)
            dt = self._compute_time_step(total_rate)

            # Compute the physics update flags (the winner rank decides for everyone)
            # Using the updated time
            next_time = self.current_time + dt
            next_step = self.current_step + 1
            if self.physics is not None:
                param_flags, field_flags, global_flag = self.physics.check_updates(
                    next_step, next_time)

        # Step 2: broadcast the changed objects and the physics decision (no serialization)
        # [optimization] Everything travels in one broadcast
        # The physics changes go with it
        event_type_str = None
        if self.rank == winner_rank and event is not None:
            event_type_str = self._resolve_event_type_name(event)

        (changed_arr, event_type, dt_out, param_flags_out,
         field_flags_out, global_flag_out, _, _,
         param_changes_arr, field_deltas_arr) = self._bcast_changed_objects_zero_copy(
            changed_objects, root=winner_rank, event_type=event_type_str,
            dt=dt, param_update_flags=param_flags, field_update_flags=field_flags,
            global_update_flag=global_flag, event_category=event_category, local_idx=local_idx,
            physics_param_changes=physics_param_changes,
            physics_field_deltas=physics_field_deltas)

        # [pair-inc] Keep this step's packet (old coordinates included) so the next build
        # can compute the zone. An empty packet is kept too: it says 'nothing changed'
        self._pair_changed_arr = changed_arr

        # Step 3: update the local object pool (incrementally)
        # Wrapped inside rma_object_pool.apply_changed_objects()
        # Only the objects in changed_arr are touched - O(delta) instead of the old O(N) sort_and_sync()
        changed_ids = self.rma_object_pool.apply_changed_objects(
            changed_arr, self.domain_decomp)

        # Step 4: record the incremental update
        self.incremental_manager.mark_objects_changed(changed_ids)

        # Step 4.5: record the changed objects (to clear ghost events next step)
        # Idea: the objects changed or deleted in step N have their ghost events cleared before step N+1 builds
        # Reason: the object data embedded in those events is stale and must be rebuilt
        # Note: only needed with the incremental update on; a full rebuild leaves no ghosts
        if self.incremental_manager.enabled and len(changed_arr) > 0:
            # [fix] Mark only the genuinely deleted objects (active=False)
            deleted_mask = ~changed_arr['active']
            deleted_obj_ids = changed_arr[deleted_mask]['id'].tolist()
            if len(deleted_obj_ids) > 0:
                self.incremental_manager.mark_objects_deleted(deleted_obj_ids)

        # [fix] Step 4.6: clear the ghost events at once (on every rank)
        # The core problem: after runtime load balancing an event may sit on any rank
        # so a changed or deleted object must have its stale events cleared everywhere
        # Note: only needed with the incremental update on; a full rebuild leaves no ghosts
        if self.incremental_manager.enabled and len(changed_arr) > 0:
            # Collect the IDs of every changed object
            changed_obj_ids = changed_arr['id']

            if len(changed_obj_ids) > 0:
                # [perf] As in _build_events step 0: the pool-level cleanup is only needed
                # with an event-moving LB present; with the LB off the build path filters the
                # invalid events itself and this is pure redundancy (measured at ~29 ms/step
                # at np = 4, exactly cancelling what the in-place construction saved)
                if self._ghost_cleanup_needed():
                    # Clear the ghost events in the single-object pool (JIT scan + swap-remove)
                    self.rma_event_pool.remove_events_for_objects(changed_obj_ids)

                # Remove the changed objects from migrated_obj_ids
                self.incremental_manager.migrated_obj_ids.difference_update(changed_obj_ids)

        # Update the ghost cache incrementally (removing the RMA traffic of the next step)
        # Idea: every rank received changed_arr and can update its cache locally
        if len(changed_arr) > 0:
            self.rma_object_pool.update_ghost_cache_incremental(changed_arr)

        # Event hooks of the post-processor (on every rank, from the same broadcast data):
        # observers such as counters derive their state from the message itself, so no
        # reduction is needed later and nothing here touches the physics or rebuild flags
        if self.post_processor.event_hooks:
            self.post_processor.on_event(
                event_type, changed_arr, self.current_step, self.current_time,
                self.rma_object_pool, self.config)

        # Apply the broadcast physics changes (on every rank)
        # Idea: the winner rank called physics.set_param_in_event() and friends inside
        # execute_func; those changes were collected, broadcast with changed_objects and
        # [rate-invalidation] A physics change never rebuilds the event structure: the
        # names of what changed are collected here and mapped, at the end, onto the
        # event classes whose rates depend on them (rates -> TODO, cached params
        # refreshed). A parameter no rate depends on (a counter, say) costs nothing.
        changed_param_names: List[str] = []
        changed_field_names: List[str] = []
        physics_scope_all = False
        physics_event_changed = False
        if self.physics is not None and (len(param_changes_arr) > 0 or len(field_deltas_arr) > 0):
            # Convert the numpy arrays into lists
            param_changes = [(int(p['param_idx']), float(p['value'])) for p in param_changes_arr]
            field_deltas = [(int(f['field_idx']), float(f['x']), float(f['y']), float(f['z']),
                            float(f['delta']), float(f['radius'])) for f in field_deltas_arr]

            # Apply the changes (every rank uses the same data, so they stay consistent)
            physics_event_changed = self.physics.apply_pending_changes(param_changes, field_deltas)
            if physics_event_changed:
                changed_param_names.extend(
                    self.physics.get_param_name(idx) for idx, _ in param_changes)
                changed_field_names.extend(
                    self.physics.get_field_name(f[0]) for f in field_deltas)

            if physics_event_changed and self.verbose and self.rank == 0:
                print(f"Step {self.current_step}: Applied {len(param_changes)} param changes, "
                      f"{len(field_deltas)} field deltas from event execution")

        # Step 5: event-triggered field updates
        # Some events (a cascade, say) force a field update once they execute
        # Design: the trigger follows the event type, not a random condition such as defect_count
        # event_type was broadcast in step 2 by _bcast_changed_objects_zero_copy
        event_triggered_rebuild = False
        if self.physics is not None:
            changed_summary = self._build_physics_changed_summary(changed_arr)
            # Build event_data (derived from the local data we already have)
            # changed_ids comes from the broadcast changed_arr, so every rank agrees
            event_data = {
                'type': event_type,
                'obj_ids': changed_ids,
                'step': self.current_step,
                'time': self.current_time,
                'changed_summary': changed_summary,
            }

            # Tell the physics module the event executed
            self.physics.notify_event_executed(event_type, event_data)

            # Process the pending field updates
            if self.physics.has_pending_triggers():
                triggered_fields = self.physics.get_pending_trigger_fields()
                object_data = self.rma_object_pool.get_local_objects()
                if self.physics.process_pending_triggers(
                    self.current_step,
                    self.current_time,
                    object_data
                ):
                    # A field changed: the rates depending on it are invalidated below
                    event_triggered_rebuild = True
                    changed_field_names.extend(triggered_fields)
                    if self.verbose and self.rank == 0:
                        print(f"Event '{event_type}' triggered field update")

        # Step 6: periodic physics update (using the broadcast decision)
        # Every rank uses the same flags, which removes the deadlock risk
        physics_changed = False
        if self.physics is not None:
            # [fix] Does any word of the extended flag array request an update?
            has_updates = (np.any(param_flags_out > 0) or np.any(field_flags_out > 0) or global_flag_out)
            if has_updates:
                # Use the updated time
                next_time = self.current_time + dt_out
                next_step = self.current_step + 1
                physics_changed = self.physics.apply_updates(
                    next_step, next_time,
                    param_flags_out, field_flags_out, global_flag_out)
                if physics_changed:
                    # The flags are the broadcast decision, identical on every rank, so
                    # deriving the scope from them keeps the invalidation consistent
                    changed_param_names.extend(
                        self.physics.get_param_name(i) for i in self._flag_indices(param_flags_out))
                    changed_field_names.extend(
                        self.physics.get_field_name(i) for i in self._flag_indices(field_flags_out))
                    if global_flag_out:
                        # a global update_func may have changed anything
                        physics_scope_all = True

        # [rate-invalidation] Map the physics changes onto the dependent event classes.
        # Nothing here sets a force-rebuild flag: the event structure depends on the
        # objects and the geometry only, so a physics change invalidates rates (and
        # refreshes cached params) and the next build keeps its incremental paths.
        rates_invalidated = False
        if event_triggered_rebuild or physics_changed or physics_event_changed:
            rates_invalidated = self._invalidate_rates_for_physics(
                changed_param_names, changed_field_names, everything=physics_scope_all)

        return dt_out, rates_invalidated

    def _compute_time_step(self, total_rate: float) -> float:
        """
        Compute the time step (KMC)

        This method is now called only by the winner rank inside _execute_event;
        dt reaches every rank through the header of _bcast_changed_objects_zero_copy,
        so the internal MPI broadcast was removed
        """
        if total_rate <= 0:
            return float('inf')

        # dt = -ln(rand) / R
        # Use the globally consistent generator (state=2 marks the time advance)
        r = self.rng.random_for_time_step()
        # Avoid log(0)
        if r == 0:
            r = 1e-10

        dt = -np.log(r) / total_rate

        # Detect an unusually large time step - it may mean ghost events in the pool
        # Commented out: this check misfires on a physically reasonable low-rate state
        # When the rate is very small (< 1e-10) every object behind the fast events may be
        # deleted while the event pool still holds the slow ghosts
        # if dt > 1e6:
        # if self.rank == 0:
        # print(f"[Warning] Step {self.current_step}: Abnormally large dt={dt:.3e}s (rate={total_rate:.3e}, r={r:.3e})")
        # print(f"[Warning] This may indicate ghost events in the event pool. Terminating simulation.")
        # # Return something larger than max_time so the main loop ends naturally
        # return float('inf')

        return dt

    def _collect_stats(self) -> Dict[str, Any]:
        """Collect and return the statistics"""
        # Collect the statistics of every rank
        total_events = self.comm.reduce(self.stats['total_events'], op=MPI.SUM, root=0)

        # Average timings
        avg_build = self.comm.reduce(self.stats['build_time'], op=MPI.SUM, root=0)
        avg_rate = self.comm.reduce(self.stats['rate_time'], op=MPI.SUM, root=0)
        avg_select = self.comm.reduce(self.stats['select_time'], op=MPI.SUM, root=0)
        avg_exec = self.comm.reduce(self.stats['execute_time'], op=MPI.SUM, root=0)

        object_count = self.comm.reduce(self.rma_object_pool.get_local_count(), op=MPI.SUM, root=0)

        stats = {
            'total_steps': self.current_step,
            'total_time': self.current_time,
            'total_events': total_events if self.rank == 0 else 0,
            'object_count': object_count if self.rank == 0 else 0,
            'avg_build_time': (avg_build / self.size / max(1, self.current_step)) if self.rank == 0 else 0,
            'avg_rate_time': (avg_rate / self.size / max(1, self.current_step)) if self.rank == 0 else 0,
            'avg_select_time': (avg_select / self.size / max(1, self.current_step)) if self.rank == 0 else 0,
            'avg_execute_time': (avg_exec / self.size / max(1, self.current_step)) if self.rank == 0 else 0,
        }

        # Add the object classification timing
        if 'classify_time' in self.stats:
            avg_classify = self.comm.reduce(self.stats['classify_time'], op=MPI.SUM, root=0)
            if self.rank == 0:
                stats['classify_time'] = avg_classify / self.size / max(1, self.current_step)

        return stats

    def destroy(self):
        """Destroy the engine and release its resources"""
        self.rma_object_pool.destroy()
        self.rma_event_pool.destroy()
        self.runtime_load_balancer.destroy()

        # Release the custom dtypes
        # MPI.Datatype.Free() ... (mpi4py manages this itself; explicit release is nicer but optional)

        if self.verbose and self.rank == 0:
            print("OKMC Engine Destroyed")


