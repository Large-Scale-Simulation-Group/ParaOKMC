"""
Core engine (three-way storage architecture)

The main OKMC engine: it ties every module together into the full simulation loop

Main loop:
Step 0: initialize the objects
Step 1: build the events (cell-based, three-way storage)
Step 2: evaluate the rates (runtime load balancing supported)
Step 3: select an event (prefix sum + binary search)
Step 4: execute the event
Step 5: advance the time
Step 5.5: external field coupling and post-processing

Core architecture:
- objects in three classes: center (local), boundary (RMA), large (broadcast globally)
- cell-based event construction: O(N_boundary) communication, O(sum N_cell log N_cell) work
- only boundary objects are pulled: 50-80% less RMA traffic
- large objects are synchronized globally: detected automatically and broadcast

Inherited features:
- self-contained events: the object data is embedded in the event
- dynamic dtype: generated by TypeCompiler
- external field coupling: three coupling modes
- runtime load balancing: CAS work stealing
"""

