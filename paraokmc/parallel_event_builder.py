def fast_deterministic_hash(id1: int, id2: int, type_index: int = 0) -> int:
    """
    Fast deterministic hash function (replacing MD5)

    Mixes bits with large primes, guaranteeing:
    1. determinism: the same input always gives the same output
    2. dispersion: different inputs give different outputs (collisions are very unlikely)
    3. cross-process consistency: every rank hashes an input identically

    Args:
        id1: first object ID (sorted, the smaller one)
        id2: second object ID (sorted, the larger one)
        type_index: index of the event type

    Returns:
        the deterministic hash (a non-negative 64-bit integer)
    """
    PRIME1 = 73856093
    PRIME2 = 19349663
    PRIME3 = 83492791
    return ((id1 * PRIME1) ^ (id2 * PRIME2) ^ (type_index * PRIME3)) & 0x7FFFFFFFFFFFFFFF

class ParallelEventBuilder:
    """
    Parallel event builder (three-way storage architecture)

    Core features:
    - fetch boundary objects from the ghost region (boundary_objects only)
    - cell-based pair event construction (O(sum N_cell log N_cell))
    - self-contained events (the full object data is embedded)
    """

    def __init__(self, domain_decomp: DomainDecomposition,
                 config: dict,
                 object_dtype: Optional[np.dtype] = None,
                 event_dtype: Optional[np.dtype] = None,
                 verbose: bool = False):
        """
        Initialize the parallel event builder

        Args:
            domain_decomp: domain decomposition object (the fine grid must be enabled)
            config: configuration dict holding the event construction functions
            object_dtype: object data type (OBJECT_DTYPE by default)
            event_dtype: event data type (EVENT_DTYPE by default)
            verbose: whether to print details
        """
        self.domain_decomp = domain_decomp
        self.comm = domain_decomp.comm
        self.rank = domain_decomp.rank
        self.size = domain_decomp.size
        self.config = config
        self.verbose = verbose

        # Dynamic dtype support
        self.object_dtype = object_dtype if object_dtype is not None else OBJECT_DTYPE
        self.event_dtype = event_dtype if event_dtype is not None else EVENT_DTYPE

        # Cell-based construction is the only mode and requires the fine grid
        if not domain_decomp.use_fine_mesh:
            raise ValueError("v1.6.6 requires domain_decomp.use_fine_mesh=True")

        # Inject the dtypes into config so user functions can read them
        self.config['_event_dtype'] = self.event_dtype
        self.config['_object_dtype'] = self.object_dtype

        # Detect the self-contained event mode
        self.is_self_contained = 'objects' in self.event_dtype.names
        if self.verbose and self.rank == 0:
            print("[ParallelEventBuilder] Cell-based mode (three-way storage)")
            if self.is_self_contained:
                print("  Mode: Self-contained events (embedding object data)")
            else:
                print("  Mode: Reference events (using obj_ids)")

        # Read the event construction functions from the configuration
        self.zero_obj_builders = config.get('zero_obj_builders', {})
        self.single_obj_builders = config.get('single_obj_builders', {})
        self.pair_type_filters = config.get('pair_type_filters', {})
        self.pair_param_extractors = config.get('pair_param_extractors', {})

        # Event weights (used by predictive load balancing)
        self.event_weights = config.get('event_weights', {})

        # Maximum interaction distance (for the KD-tree query)
        self.max_interaction_distance = domain_decomp.max_interaction_distance

        # Vectorized filter configuration
        # Format: {event_type: {'type_pairs': [(t1, t2), ...], 'max_distance': float}}
        self.vectorized_pair_filters = config.get('vectorized_pair_filters', {})

        # Create the global vectorized builder instance
        # cKDTree + query_pairs + vectorized filtering are enabled by default
        self._vectorized_builder = VectorizedPairEventBuilder(
            domain_decomp=domain_decomp,
            config=config,
            object_dtype=self.object_dtype,
            event_dtype=self.event_dtype,
            verbose=verbose
        )
        if self.verbose and self.rank == 0:
            print(f"  Vectorized event builder (cKDTree): enabled")

        # Vectorized single-object event builder (JIT + prange)
        self._vectorized_single_builder = VectorizedSingleEventBuilder(
            domain_decomp=domain_decomp,
            config=config,
            object_dtype=self.object_dtype,
            event_dtype=self.event_dtype,
            verbose=verbose
        )
        if self.verbose and self.rank == 0:
            print(f"  Vectorized single event builder (JIT LUT): enabled")

        # Vectorized zero-object event builder (per_cell mode)
        self._vectorized_zero_builder = VectorizedZeroEventBuilder(
            domain_decomp=domain_decomp,
            config=config,
            event_dtype=self.event_dtype,
            verbose=verbose
        )
        if self.verbose and self.rank == 0 and self._vectorized_zero_builder.has_per_cell_events():
            print(f"  Vectorized zero event builder (per_cell): enabled")

        # Build the event type name -> index mapping (used for ID generation)
        self._build_event_type_mapping()

        # Keep every object (local + ghost) for the rate evaluation
        self.all_objects = None  # NumPy array
        self._all_objects_dict = {}  # id -> object dict (lazy, see the property)

    @property
    def all_objects_dict(self):
        """id -> object dict (built lazily).

        [performance fix] Only _embed_objects_from_ids / _embed_objects_batch look
        objects up by id; the vectorized single/pair paths index directly. It used to
        be built unconditionally (~78 ms/step at N=1e5) and often went unused.
        """
        if self._all_objects_dict is None:
            objs = self.all_objects
            self._all_objects_dict = (
                {int(o['id']): o for o in objs} if objs is not None else {}
            )
        return self._all_objects_dict

    @all_objects_dict.setter
    def all_objects_dict(self, value):
        self._all_objects_dict = value

    def _resolve_event_type_name(self, event) -> str:
        if 'event_type_id' in event.dtype.names:
            event_type_id = int(event['event_type_id'])
            event_name = self.config.get('_event_int_to_name', {}).get(event_type_id)
            if event_name is not None:
                return event_name
        if 'type' in event.dtype.names:
            return str(event['type']).strip()
        return ''

    def _build_event_type_mapping(self):
        """
        Build the event type name -> index mapping (used for ID generation)

        Each event class (zero/single/pair) has its own type index space
        """
        self.single_event_types = {}
        self.pair_event_types = {}
        self.zero_event_types = {}

        # Collect every single-object event type
        for event_name in self.single_obj_builders.keys():
            idx = len(self.single_event_types)
            assert idx < (1 << 10), f"Single event types exceed 10-bit limit (1024)"
            self.single_event_types[event_name] = idx

        # Collect every pair event type
        for event_name in self.pair_type_filters.keys():
            idx = len(self.pair_event_types)
            self.pair_event_types[event_name] = idx

        # Collect every zero-object event type
        for event_name in self.zero_obj_builders.keys():
            idx = len(self.zero_event_types)
            assert idx < (1 << 16), f"Zero event types exceed 16-bit limit (65536)"
            self.zero_event_types[event_name] = idx

    # ===== 128-bit event ID generators (bit-field layout) =====

    def _generate_single_obj_event_id_128(self, obj_id: int, event_type: str,
                                           current_step: int = 0) -> Tuple[int, int]:
        """
        Generate the 128-bit ID of a single-object event

        Layout:
        - high 64 bits: [0:1][prefix:2][step:35][rank:16][event type:10]
        - low 64 bits: obj_id (the full 64 bits, never truncated)

        Args:
            obj_id: global ID of the object (full 64 bits)
            event_type: name of the event type
            current_step: current step

        Returns:
            (id_high, id_low) - the high and low 64 bits of the 128-bit ID
        """
        # Index of the event type
        type_index = self.single_event_types.get(event_type, 0)

        # Validate the bit-field ranges
        assert 0 <= current_step < (1 << 35), f"Step {current_step} exceeds 35-bit limit"
        assert 0 <= self.rank < (1 << 16), f"Rank {self.rank} exceeds 16-bit limit"
        assert 0 <= type_index < (1 << 10), f"TypeIndex {type_index} exceeds 10-bit limit"

        # Build the high 64 bits: [0:1][prefix:2][step:35][rank:16][event type:10]
        # prefix = 00 (single-object event)
        prefix = 0  # 00 in binary
        id_high = (prefix << 61) | (current_step << 26) | (self.rank << 10) | type_index

        # Build the low 64 bits: the complete object ID (never truncated)
        id_low = int(obj_id)

        return (int(id_high), int(id_low))

    def _generate_pair_obj_event_id_128(self, obj1_id: int, obj2_id: int,
                                        event_type: str, current_step: int,
                                        index: int = 0) -> Tuple[int, int]:
        """
        Generate the 128-bit ID of a pair event

        Layout:
        - high 64 bits: [0:1][prefix:2][step:35][rank:16][event type:10]
        - low 64 bits: index (sequence number within one type, keeping IDs unique)

        Args:
            obj1_id, obj2_id: global IDs of the two objects (already normalized)
            event_type: name of the event type
            current_step: current step
            index: sequence number within this event type

        Returns:
            (id_high, id_low) - the high and low 64 bits of the 128-bit ID
        """
        # Index of the event type
        type_index = self.pair_event_types.get(event_type, 0)

        # Validate the bit-field ranges
        assert 0 <= current_step < (1 << 35), f"Step {current_step} exceeds 35-bit limit"
        assert 0 <= self.rank < (1 << 16), f"Rank {self.rank} exceeds 16-bit limit"
        assert 0 <= type_index < (1 << 10), f"TypeIndex {type_index} exceeds 10-bit limit"

        # Build the high 64 bits: [0:1][prefix:2][step:35][rank:16][event type:10]
        prefix = 1  # 01 in binary
        id_high = (prefix << 61) | (current_step << 26) | (self.rank << 10) | type_index

        # [fix] The sequence number is used as id_low to keep IDs unique
        id_low = index + 1  # starts at 1; 0 is reserved for zero-object events

        return (int(id_high), int(id_low))

    def _generate_zero_obj_event_id_128(self, event_type: str, index: int,
                                        current_step: int = 0) -> Tuple[int, int]:
        """
        Generate the 128-bit ID of a zero-object event

        Layout:
        - high 64 bits: [0:1][prefix:2][step:35][rank:16][event type:10]
        - low 64 bits: index (full 64 bits, so vast numbers of zero events fit)

        Args:
            event_type: name of the event type
            index: sequence number (the n-th event of this type)
            current_step: current step

        Returns:
            (id_high, id_low) - the high and low 64 bits of the 128-bit ID
        """
        # Index of the event type
        type_index = self.zero_event_types.get(event_type, 0)

        # Validate the bit-field ranges
        assert 0 <= current_step < (1 << 35), f"Step {current_step} exceeds 35-bit limit"
        assert 0 <= self.rank < (1 << 16), f"Rank {self.rank} exceeds 16-bit limit"
        assert 0 <= type_index < (1 << 10), f"TypeIndex {type_index} exceeds 10-bit limit"
        # index is 64-bit now, so it is unbounded
        assert 0 <= index < (1 << 63), f"Index {index} exceeds 63-bit limit"

        # Build the high 64 bits: [0:1][prefix:2][step:35][rank:16][event type:10]
        # prefix = 10 (zero-object event)
        prefix = 2  # 10 in binary
        id_high = (prefix << 61) | (current_step << 26) | (self.rank << 10) | type_index

        # Build the low 64 bits: the complete index
        id_low = int(index)

        return (int(id_high), int(id_low))

    def build_all_events(self, rma_object_pool: RMAObjectPool,
                         rma_event_pool: RMAEventPool,
                         changed_objects: Optional[Set[int]] = None,
                         rebuild_zero: bool = True,
                         rebuild_single: bool = True,
                         current_step: int = 0,
                         migrated_obj_ids: Optional[Set[int]] = None,
                         pair_changed_arr=None,
                         allow_pair_rate_keep: bool = False,
                         allow_single_inplace: bool = True,
                         foreign_events_hosted: bool = False) -> Tuple[int, int, int]:
        """
        Build every event (three-way architecture)

        [contract] The structural increment is always on; the only user switch is the
        class-level incremental_rate (which governs rate reuse alone):
        - zero: with rebuild_zero=False the structure is kept wholesale and the rate
          follows the class switch (DONE kept or reset to TODO; recompute by default)
        - single: structural in-place increment (driven by object flags), falling back
          to a full rebuild when the preconditions fail; retained events default to TODO
        - pair: cell-level poisoned-zone structural increment (driven by pair_changed_arr)

        Args:
            rma_object_pool: RMA object pool (three-way storage)
            rma_event_pool: RMA event pool
            changed_objects: legacy argument (the snapshot path is retired; the engine passes None)
            rebuild_zero: whether to rebuild the zero-object events
            rebuild_single: whether to rebuild the single-object events
            current_step: current step (used for 128-bit ID generation)
            pair_changed_arr: [pair-inc] the previous state packet (old coordinates included).
                When not None a cell-level poisoned-zone structural increment is attempted,
                falling back to a full rebuild if the preconditions fail
            allow_pair_rate_keep: [feat-2] lets classes with incremental_rate=True keep
                the DONE rate of structurally retained events
            allow_single_inplace: safety precondition of the single-event in-place
                increment (no global structural change / physics rebuild / runtime stealing)
            foreign_events_hosted: an event-moving LB (predictive) is on, so this pool may
                host events of objects owned elsewhere; ownership is then not a validity
                test (the engine already dropped the events of changed/deleted objects
                pool-wide from the broadcast change set)

        Returns:
            (count_zero, count_single, count_pair)
        """
        # Step 2: get the local objects (center + boundary + large)
        local_objects = rma_object_pool.get_all_objects_including_large()

        # Keep every object for the rate evaluation (including copies of the large objects)
        # [performance fix] all_objects_dict is built lazily: only
        # _embed_objects_from_ids / _embed_objects_batch consume it, while the vectorized
        # single-object path indexes objects[object_indices] directly and never looks in
        # the dict. Building 100k entries every step cost ~78 ms and was usually wasted.
        self.all_objects = local_objects
        self._all_objects_dict = None   # see the all_objects_dict property

        # Step 3: build the zero-object events
        if rebuild_zero:
            rma_event_pool.clear_rate_sum('zero')
            # 3a: global-mode zero-object events (the traditional builder_func)
            zero_events = self._build_zero_obj_events(local_objects, local_objects, current_step)

            # 3b: per_cell-mode zero-object events (vectorized builder)
            per_cell_events = self._vectorized_zero_builder.build_zero_events(
                self.config, current_step)

            # Merge global + per_cell
            all_zero = []
            if zero_events:
                all_zero.append(np.array(zero_events, dtype=self.event_dtype))
            if len(per_cell_events) > 0:
                all_zero.append(per_cell_events)

            if all_zero:
                combined_zero = np.concatenate(all_zero)
            else:
                combined_zero = np.array([], dtype=self.event_dtype)

            rma_event_pool.set_zero_obj_events(combined_zero, recompute_rate_sum=False)
        else:
            # [contract] The structure is kept wholesale, but rate reuse follows the
            # class-level incremental_rate: a class without it drops to TODO and is
            # recomputed each step (a zero event rate may depend on time or a field,
            n_zero = rma_event_pool.count_zero
            if n_zero > 0:
                zero_events = rma_event_pool.zero_obj_array[:n_zero]
                hold = np.zeros(n_zero, dtype=np.bool_)
                lut = getattr(self._vectorized_single_builder,
                              '_rate_incremental_by_global', None)
                if lut is not None and 'event_type_id' in zero_events.dtype.names:
                    gids = zero_events['event_type_id']
                    in_range = (gids >= 0) & (gids < len(lut))
                    hold[in_range] = lut[gids[in_range]]
                rma_event_pool.reset_zero_statuses(hold)
        count_zero = rma_event_pool.count_zero

        # Step 4: build the single-object events
        # Vectorized builder (JIT LUT + prange + batch create)
        if rebuild_single:
            rma_event_pool.clear_rate_sum('single')
            # Build single-object events only for locally owned objects
            owned_objects = local_objects[local_objects['owner_rank'] == self.rank]

            # [fix] Deduplicate by ID: one object may sit in both the center/boundary and large arrays
            # A duplicate would create the same (id_high, id_low) event twice
            if len(owned_objects) > 0:
                _, unique_idx = np.unique(owned_objects['id'], return_index=True)
                if len(unique_idx) < len(owned_objects):
                    owned_objects = owned_objects[np.sort(unique_idx)]

            # [performance fix] The structural in-place update path
            # The structure of a single-object event depends only on whether the object
            # exists and on its type, and one KMC step changes only the objects of the
            # executed event. The old code rebuilt the whole event array every step, even
            # with the incremental update off; now only changed objects are rebuilt and the
            # rest stay in place (retained events default to TODO; a class with
            # incremental_rate=True keeps DONE). [fix] allow_single_inplace comes from the
            # engine: a global structural change (repartition), a physics-forced rebuild or
            # an event-moving LB (predictive/runtime) disables it, because the in-place
            # invariant is 'this pool is exactly the events of this rank's objects', which
            # all three break: an incoming object carries no flag and freezes; a moved event
            # is rebuilt by nobody and is lost; a SENT husk reset to TODO is double counted
            inplace_done = False
            if (allow_single_inplace
                    and current_step > 0
                    and (rma_event_pool.count_single > 0 or foreign_events_hosted)
                    and 'new' in owned_objects.dtype.names
                    and 'changed' in owned_objects.dtype.names
                    and 'obj_ids' in self.event_dtype.names):
                stale_mask = owned_objects['new'] | owned_objects['changed']
                # In-place updating only pays off when few objects changed. With an
                # event-moving LB it is mandatory whatever the counts: a *local* full rebuild
                # is wrong, not merely slow - it drops the foreign events hosted here (a rank
                # owning nothing would rebuild an empty pool) and re-creates the owned events
                # that currently live on another rank (duplicates). Only a global full rebuild
                # taken by every rank at once (allow_single_inplace=False) is consistent.
                if foreign_events_hosted or int(np.count_nonzero(stale_mask)) * 4 < len(owned_objects):
                    stale_ids = np.unique(
                        np.ascontiguousarray(owned_objects['id'][stale_mask], dtype=np.int64))
                    valid_ids = np.unique(
                        np.ascontiguousarray(owned_objects['id'], dtype=np.int64))

                    n_ev = rma_event_pool.count_single
                    ev_arr = rma_event_pool.single_obj_array[:n_ev]
                    ev_obj_ids = np.ascontiguousarray(
                        ev_arr['obj_ids'][:, 0], dtype=np.int64)
                    keep = np.empty(n_ev, dtype=np.int8)
                    if foreign_events_hosted:
                        # [event-LB] keep foreign events too; only this rank's changed
                        # objects are stale here (structure only: status falls back to
                        # TODO in update_single_events_inplace unless incremental_rate)
                        jit_mark_stale_single_events_any_owner(ev_obj_ids, stale_ids, keep)
                    else:
                        jit_mark_stale_single_events(ev_obj_ids, valid_ids, stale_ids, keep)
                    keep_mask = keep.astype(np.bool_)

                    # [feat-2] Class-level rate increment: a class with incremental_rate=True
                    # may keep the DONE rate of retained events; the rest drop to TODO
                    keep_rate_mask = None
                    lut = getattr(self._vectorized_single_builder,
                                  '_rate_incremental_by_global', None)
                    if lut is not None and 'event_type_id' in ev_arr.dtype.names:
                        gids = ev_arr['event_type_id']
                        keep_rate_mask = np.zeros(n_ev, dtype=np.bool_)
                        in_range = (gids >= 0) & (gids < len(lut))
                        keep_rate_mask[in_range] = lut[gids[in_range]]

                    # Rebuild the events of changed and new objects only
                    rebuilt = self._vectorized_single_builder.build_single_events(
                        owned_objects[stale_mask], None, current_step,
                        migrated_obj_ids=None)

                    rma_event_pool.update_single_events_inplace(
                        keep_mask, rebuilt, keep_rate_mask=keep_rate_mask)
                    inplace_done = True

            if inplace_done:
                count_single = rma_event_pool.count_single
                single_events_array = None
            else:
                single_events_array = self._vectorized_single_builder.build_single_events(
                    owned_objects, changed_objects, current_step,
                    migrated_obj_ids=migrated_obj_ids)

            # [DEBUG] Check single_events_array for duplicate event IDs
            # [performance fix] Only under verbose: this check runs a Python loop plus
            # np.unique over every single event, costing milliseconds when events are many.
            if (self.verbose and single_events_array is not None
                    and len(single_events_array) > 0
                    and 'id_high' in single_events_array.dtype.names):
                eids = np.array([(int(e['id_high']), int(e['id_low'])) for e in single_events_array])
                _, uidx = np.unique(eids, axis=0, return_index=True)
                if len(uidx) < len(single_events_array):
                    n_dup = len(single_events_array) - len(uidx)
                    # Find the duplicate IDs
                    from collections import Counter
                    eid_tuples = [(int(e['id_high']), int(e['id_low'])) for e in single_events_array]
                    dup_ids = [k for k, v in Counter(eid_tuples).items() if v > 1]
                    print(f"[Rank {self.rank}] [DEBUG] step={current_step} {n_dup} duplicate event IDs in single_events_array! changed_objects={'None' if changed_objects is None else len(changed_objects)}")
                    for did in dup_ids[:5]:
                        # Find the type and obj_ids of the duplicated events
                        matches = [e for e in single_events_array
                                   if int(e['id_high']) == did[0] and int(e['id_low']) == did[1]]
                        print(f"  dup ID {did}: {len(matches)} copies, "
                              f"types={[self._resolve_event_type_name(m) for m in matches]}")
                    # Check owned_objects for duplicates too
                    obj_ids = owned_objects['id']
                    _, obj_uidx = np.unique(obj_ids, return_index=True)
                    print(f"  owned_objects: {len(owned_objects)} total, {len(obj_uidx)} unique IDs")

            # The in-place path already wrote the pool (status/rate reset included)
            if not inplace_done:
                rma_event_pool.set_single_obj_events(single_events_array, recompute_rate_sum=False)
                rma_event_pool.set_rate_sum(
                    'single',
                    float(getattr(self._vectorized_single_builder, 'last_reused_rate_sum', 0.0))
                )
        count_single = rma_event_pool.count_single

        # Step 5: build the pair events
        # [pair-inc] Try the cell-level poisoned-zone increment first (falling back automatically)
        pair_incremental_done = False
        if pair_changed_arr is not None:
            pair_incremental_done = self._vectorized_builder.build_pair_events_incremental(
                rma_object_pool, rma_event_pool, pair_changed_arr,
                current_step, allow_rate_keep=allow_pair_rate_keep)

        if not pair_incremental_done:
            # cKDTree + query_pairs + vectorized filtering (the full path)
            rma_event_pool.clear_rate_sum('pair')
            pair_events_array = self._vectorized_builder.build_pair_events(
                rma_object_pool, current_step
            )
            rma_event_pool.set_pair_obj_events(pair_events_array, recompute_rate_sum=False)

        # Refresh the all_objects reference (used by the rate evaluation; the dict stays lazy)
        self.all_objects = self._vectorized_builder.all_objects
        self._all_objects_dict = None
        count_pair = rma_event_pool.count_pair

        return (count_zero, count_single, count_pair)


    def _build_zero_obj_events(self, local_objects: np.ndarray,
                                all_objects: np.ndarray,
                                current_step: int = 0) -> List[np.ndarray]:
        """
        Build the zero-object events (e.g. cascade)

        Incremental strategy (refined):
        - a global state change forces a rebuild, but the old event structure can be reused with status 2 -> 0

        Args:
            local_objects: the local objects
            all_objects: every object (local + ghost)
            current_step: current step (used to put the step into the event ID)

        Returns:
            the list of zero-object events
        """
        events = []
        self.last_reused_single_rate_sum = 0.0

        # Build the event_type -> old event map (for reuse)
        old_events_map = {}
        if hasattr(self, 'prev_zero_events') and len(self.prev_zero_events) > 0:
            for old_event in self.prev_zero_events:
                event_type = self._resolve_event_type_name(old_event)
                old_events_map[event_type] = old_event

        for event_type, builder_func in self.zero_obj_builders.items():
            type_events = builder_func(local_objects, all_objects, self.config, self.rank)

            for idx, event in enumerate(type_events):
                # [fix] Regenerate the 128-bit ID
                id_high, id_low = self._generate_zero_obj_event_id_128(event_type, idx, current_step)

                # Can the old event be reused?
                if event_type in old_events_map:
                    # Reuse the old event but with the new parameters (Bug B fix)
                    old_event = old_events_map[event_type].copy()
                    # [fix] Use the 128-bit ID
                    if 'id_high' in self.event_dtype.names:
                        old_event['id_high'] = id_high
                    if 'id_low' in self.event_dtype.names:
                        old_event['id_low'] = id_low
                    old_event['id'] = 0  # a 128-bit ID event sets the 'id' field to 0
                    old_event['params'] = event['params']  # use the new parameters (the key fix)
                    old_event['status'] = 0  # the rate must be recomputed
                    old_event['owner_rank'] = -1  # a zero-object event always has owner_rank = -1
                    events.append(old_event)
                else:
                    # A new event: make sure owner_rank = -1
                    # [fix] Use the 128-bit ID
                    if 'id_high' in self.event_dtype.names:
                        event['id_high'] = id_high
                    if 'id_low' in self.event_dtype.names:
                        event['id_low'] = id_low
                    event['id'] = 0  # a 128-bit ID event sets the 'id' field to 0
                    event['owner_rank'] = -1
                    events.append(event)

        return events

    def _build_single_obj_events(self, local_objects: np.ndarray,
                                  changed_objects: Optional[Set[int]] = None,
                                  current_step: int = 0) -> List[np.ndarray]:
        """
        Build the single-object events (the O(delta) optimized version)

        Guiding idea: keep what did not change, patch only what did

        Mode A (full rebuild) - when changed_objects=None:
            - triggered by: initialization, a sharp temperature change, other global changes
            - action: call builder_func for every object and build fresh events

        Mode B (incremental) - when changed_objects is a set:
            - triggered by: an ordinary step where only some objects changed
            - action:
              1. select the subset of changed objects (a NumPy mask, O(N))
              2. call builder_func for the changed objects only (O(delta))
              3. reuse the events of unchanged objects from the snapshot and reset their status (O(M), M = old event count)

        Args:
            local_objects: the local objects (a NumPy array)
            changed_objects: set of changed object IDs (None = full, set = incremental)
            current_step: current step (used to put the step into the event ID)

        Returns:
            the list of single-object events (a list of NumPy arrays)

        Performance:
            - full mode: O(N), N = number of objects
            - incremental mode: O(delta + M), delta = changed objects, M = old event count
            - with delta << N the gain is large (delta=2, N=1000 gives a 500x speed-up)
        """
        events = []

        # ===== Mode A: full rebuild =====
        if changed_objects is None:
            # [optimization] Collect the events of every builder, then post-process in bulk
            all_type_events = []  # [(event_type, events_list), ...]

            for event_type, builder_func in self.single_obj_builders.items():
                type_events = builder_func(local_objects, self.config, self.rank)
                all_type_events.append((event_type, type_events))

            # Post-process every event in bulk
            events = self._batch_postprocess_single_events(all_type_events, current_step)
            return events

        # ===== Mode B: incremental build (the O(delta) optimization) =====

        # Step 1: select the subset of changed objects (a NumPy mask, O(N))
        if len(changed_objects) > 0:
            changed_ids_list = list(changed_objects)
            mask = np.isin(local_objects['id'], changed_ids_list)
            objects_to_build = local_objects[mask]
        else:
            # Nothing changed: reuse every old event
            objects_to_build = np.array([], dtype=self.object_dtype)  # use self.object_dtype

        # Step 2: build the obj_id -> old event map (for fast lookup)
        old_events_map = {}
        if hasattr(self, 'prev_single_events'):
            for old_event in self.prev_single_events:
                obj_id = int(old_event['obj_ids'][0])
                if obj_id >= 0:
                    old_events_map[obj_id] = old_event

        # Step 3: reuse the events of unchanged objects (O(M), M = old event count)
        # Strategy: walk the old events and keep those whose object is still local and unchanged
        # Key fix: the event of a deleted object must not be reused, so it gets cleaned up
        local_obj_ids = set(local_objects['id'])  # for a quick 'is the object still local' test

        # Debugging: statistics on event reuse
        n_reused = 0
        n_discarded_deleted = 0  # the object was deleted
        n_discarded_changed = 0  # the object changed

        for old_event in self.prev_single_events if hasattr(self, 'prev_single_events') else []:
            obj_id = int(old_event['obj_ids'][0])

            # Test: the object is still local and did not change
            # If the object was deleted (obj_id in changed_objects but not in local_obj_ids)
            # the old event is not reused and is therefore cleaned up
            if obj_id in local_obj_ids and obj_id not in changed_objects:
                # Reuse the old event but reset its status (fixes the status deadlock bug)
                new_event = old_event.copy()
                if old_event['status'] == STATUS_DONE and float(old_event['rate']) >= 0.0:
                    self.last_reused_single_rate_sum += float(old_event['rate'])
                else:
                    new_event['status'] = STATUS_TODO  # [key] reset the status to pending
                # [fix] Regenerate the 128-bit ID (current_step included)
                event_type = self._resolve_event_type_name(new_event)
                id_high, id_low = self._generate_single_obj_event_id_128(obj_id, event_type, current_step)
                if 'id_high' in self.event_dtype.names:
                    new_event['id_high'] = id_high
                if 'id_low' in self.event_dtype.names:
                    new_event['id_low'] = id_low
                new_event['id'] = 0  # a 128-bit ID event sets the 'id' field to 0
                events.append(new_event)
                n_reused += 1
            else:
                # The event is dropped
                if obj_id not in local_obj_ids:
                    n_discarded_deleted += 1
                elif obj_id in changed_objects:
                    n_discarded_changed += 1

        # Many events dropped without any new event created hints at a problem
        if hasattr(self, 'prev_single_events') and len(self.prev_single_events) > 0:
            n_old = len(self.prev_single_events)
            if n_discarded_deleted > n_old * 0.5 and len(objects_to_build) == 0:
                if self.rank == 0:
                    print(f"[Warning] Step {current_step}: Large number of events discarded "
                          f"(deleted={n_discarded_deleted}, changed={n_discarded_changed}, reused={n_reused}, "
                          f"old_total={n_old}, new_to_build={len(objects_to_build)})")

        # Step 4: build fresh events for the changed objects (O(delta))
        # [optimization] Post-process in bulk
        if len(objects_to_build) > 0:
            all_type_events = []
            for event_type, builder_func in self.single_obj_builders.items():
                # Call the user function for the changed objects only
                type_events = builder_func(objects_to_build, self.config, self.rank)
                all_type_events.append((event_type, type_events))

            # Post-process the new events of the changed objects in bulk
            new_events = self._batch_postprocess_single_events(all_type_events, current_step)
            events.extend(new_events)

        return events

    def _embed_objects_into_event(self, event: np.ndarray, objects: List[np.ndarray]) -> np.ndarray:
        """
        Deep-copy the object data into the event (the core self-contained feature)

        Args:
            event: the event record (either the reference or the self-contained layout)
            objects: the participating objects (a NumPy structured array)

        Returns:
            the updated event (in self-contained mode event['objects'] is filled)

        Behaviour:
        - reference mode: nothing is changed (event['obj_ids'] is already filled)
        - self-contained mode: the object data is deep-copied into event['objects']

        Guiding idea:
        - an event becomes a self-contained unit of work
        - the rate and execute stages no longer consult the object pool
        - memory stays contiguous and JIT friendly
        """
        if not self.is_self_contained:
            # Reference-compatible mode: nothing to embed
            return event

        # Self-contained mode: deep-copy the object data
        # A NumPy structured array supports direct assignment and copies the memory itself
        for i, obj in enumerate(objects):
            if i < len(event['objects']):
                event['objects'][i] = obj  # deep-copy the object record
            else:
                break  # beyond the capacity of event['objects'], ignore the rest

        # Mark the unused object slots (with id = -1)
        for i in range(len(objects), len(event['objects'])):
            event['objects'][i]['id'] = -1
            event['objects'][i]['active'] = False

        return event

    def _embed_objects_from_ids(self, event: np.ndarray) -> np.ndarray:
        """
        Look the objects up by obj_ids and embed them into the event

        Args:
            event: the event (its obj_ids field is already filled)

        Returns:
            the updated event (in self-contained mode event['objects'] is filled)

        Note:
        - assumes self.all_objects_dict is initialized (holding every local and ghost object)
        - a slot is skipped when the object cannot be found
        """
        if not self.is_self_contained:
            return event

        # Look the object up in all_objects_dict
        objects = []
        if 'obj_ids' in self.event_dtype.names:
            for obj_id in event['obj_ids']:
                if obj_id >= 0 and obj_id in self.all_objects_dict:
                    objects.append(self.all_objects_dict[obj_id])
                else:
                    break  # an invalid ID ends the loop

        # Embed the objects
        if objects:
            return self._embed_objects_into_event(event, objects)
        else:
            return event

    def _embed_objects_batch(self, events_array: np.ndarray) -> None:
        """
        [performance] Embed the object data into the event array in bulk

        Args:
            events_array: the event array (its obj_ids field is already filled)

        Behaviour:
            - handles the embedding of every event at once
            - avoids one Python call per event
            - uses NumPy vectorization

        Expected gain: 5-10x over calling _embed_objects_from_ids one by one
        """
        if not self.is_self_contained:
            return

        if 'objects' not in self.event_dtype.names or 'obj_ids' not in self.event_dtype.names:
            return

        # Process every event in bulk
        for i, event in enumerate(events_array):
            # Look the objects up (little room for vectorization: few and variable obj_ids)
            n_objs = 0
            for k, obj_id in enumerate(event['obj_ids']):
                if obj_id >= 0 and obj_id in self.all_objects_dict:
                    # Assign into events_array directly (modified in place)
                    events_array[i]['objects'][n_objs] = self.all_objects_dict[obj_id]
                    n_objs += 1
                elif obj_id >= 0:
                    # The object does not exist: mark the slot invalid
                    events_array[i]['obj_ids'][k] = -1
                    break  # an invalid ID ends the loop
                else:
                    break  # obj_id < 0 ends the loop

            # Fill the unused object slots
            for j in range(n_objs, len(event['objects'])):
                events_array[i]['objects'][j]['id'] = -1
                events_array[i]['objects'][j]['active'] = False

    def _batch_postprocess_single_events(self, all_type_events: List[Tuple[str, List]],
                                          current_step: int) -> List[np.ndarray]:
        """
        [performance] Post-process the single-object events in bulk

        Args:
            all_type_events: [(event_type, events_list), ...] as returned by the user builders
            current_step: current step (used for ID generation)

        Returns:
            the post-processed event list

        Behaviour:
            - generates the 128-bit IDs in bulk
            - sets the statuses and fields in bulk
            - embeds the object data in bulk

        Expected gain: 3-5x over post-processing one by one
        """
        # Phase 1: count the events
        total_events = sum(len(events) for _, events in all_type_events)

        if total_events == 0:
            return []

        # Phase 2: collect every event into one list (grouped by type)
        result_events = []

        for event_type, type_events in all_type_events:
            if len(type_events) == 0:
                continue

            # Process every event of one type in bulk
            for event in type_events:
                # Set the status
                event['status'] = STATUS_TODO

                # Generate the 128-bit ID
                obj_id = int(event['obj_ids'][0])
                id_high, id_low = self._generate_single_obj_event_id_128(obj_id, event_type, current_step)

                if 'id_high' in self.event_dtype.names:
                    event['id_high'] = id_high
                if 'id_low' in self.event_dtype.names:
                    event['id_low'] = id_low
                event['id'] = 0  # 128-bit ID mode

                result_events.append(event)

        # Phase 3: embed the object data in bulk (in self-contained mode)
        if self.is_self_contained and len(result_events) > 0:
            # Convert to a NumPy array so it can be processed in bulk
            events_array = np.array(result_events, dtype=self.event_dtype)
            self._embed_objects_batch(events_array)
            return list(events_array)
        else:
            # Reference mode: embed one by one (kept for compatibility)
            for i, event in enumerate(result_events):
                result_events[i] = self._embed_objects_from_ids(event)
            return result_events


