"""
Parallel event builder (three-way storage architecture)

Core features:
1. Fetch boundary objects from neighbour ranks in bulk over RMA
2. Build the three event classes (zero-object, single-object, pair)
3. Use a cell-based approach plus mini KD-trees for the pair spatial query
4. Support the incremental update strategy

Architecture:
- only boundary objects are pulled (50-80% less RMA traffic)
- cell-based event construction (O(sum N_cell log N_cell))
- self-contained events: the object data is deep-copied into event['objects']
- dynamic dtype support (generated by TypeCompiler)

Event construction pipeline:
Step 1: get the local objects (center + boundary + large)
Step 2: fetch boundary objects from the ghost ranks over RMA
Step 3: build the zero-object events
Step 4: build the single-object events (incremental, with embedded object data)
Step 5: build the pair events (cell-based, accelerated by mini KD-trees)
Step 6: write into the RMA event pool

Design note: docs/ARCHITECTURE.md (object classification and boundary exchange)
"""

