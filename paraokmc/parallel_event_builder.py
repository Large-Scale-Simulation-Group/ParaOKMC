def default_migration_builder(objects: np.ndarray, config: dict, rank: int) -> List[np.ndarray]:
    """
    Default migration event builder

    Creates one migration event per object

    Note:
    - dynamic dtype supported: read from config['_event_dtype'] when available
    - backward compatible: without a dynamic dtype the default EVENT_DTYPE is used
    """
    # Event weight
    event_weights = config.get('event_weights', {})
    weight = event_weights.get('migration', 1.0)

    # Try to read event_dtype from config (set by ParallelEventBuilder)
    event_dtype = config.get('_event_dtype', None)

    events = []
    for i, obj in enumerate(objects):
        event = create_event(
            event_id=rank * 10000000 + i,
            event_type='migration',
            obj_ids=[int(obj['id'])],
            params=[1.0, 0.0],  # [Em, v0]
            owner_rank=rank,
            weight=weight,
            dtype=event_dtype,  # pass the dynamic dtype (None falls back to the default)
            config=config,
        )
        events.append(event)
    return events


def default_capture_filter(obj1: np.ndarray, obj2: np.ndarray, distance: float, config: dict, rank: int) -> bool:
    """
    Default capture type filter

    H and V may undergo a capture reaction

    Args:
        obj1, obj2: the participating objects
        distance: distance between the objects
        config: configuration dict
        rank: current rank
    """
    int_to_type = config.get('_int_to_type', {}) if config else {}
    type1 = int_to_type.get(int(obj1['type_id']), '')
    type2 = int_to_type.get(int(obj2['type_id']), '')
    return (type1 == 'H' and type2 == 'V') or (type1 == 'V' and type2 == 'H')


def default_capture_params(obj1: np.ndarray, obj2: np.ndarray) -> List[float]:
    """
    Default capture parameter extractor
    """
    # Compute the distance
    dx = obj1['x'] - obj2['x']
    dy = obj1['y'] - obj2['y']
    dz = obj1['z'] - obj2['z']
    distance = np.sqrt(dx**2 + dy**2 + dz**2)
    return [distance, 0.0]


